def estimated_density_at(x, final_results):
    """
    For any x in [0,1] (or within the region of interest), return the estimated density.
    Here a linear interpolation is used on the grid midpoints stored in final_results.

    Parameters:
    -----------
    x : float or array-like
        Evaluation point(s).
    final_results : dict
        Must contain "grid_midpoints" and "estimated_density".

    Returns:
    --------
    f_x : float or array of estimated density values.
    """
    f_interp = interp1d(final_results["grid_midpoints"], final_results["estimated_density"],
                        kind="linear", bounds_error=False, fill_value="extrapolate")
    return f_interp(x)

##############################################
# 4. Compute the gradient of the density
##############################################

def compute_grad_f(x, final_results,smoothness_order=1):
    """
    Compute the gradient of the estimated density at x with respect to the non-intercept coefficients.

    That is, compute
         grad_f(x) = f(x) * [φ(x) - E[φ(X)]],
    where:
         - f(x) is the estimated density at x,
         - φ(x) is the HAL basis vector evaluated at x,
         - E[φ(X)] is the expectation of the basis function vector computed over the integration grid.

    Parameters:
    -----------
    x : float
        The evaluation point.
    final_results : dict
        Must contain:
          - "grid_points_hal_selected": the selected HAL knots.
          - "b_jk": basis functions evaluated on the integration grid.
          - "estimated_density": estimated density on the integration grid.
          - "delta_j": grid interval lengths.

    Returns:
    --------
    grad_f : 1D numpy array, the gradient of f at x with respect to β.
    """
    # Evaluate f(x)
    f_x = estimated_density_at(x, final_results)
    # Evaluate basis at x:
    df_x = pd.DataFrame({'W1': [x]})
    phi_x = create_basis_functions(df_x, final_results["grid_points_hal_selected"],smoothness_order=smoothness_order).numpy().flatten()
    # Compute the expectation E[φ(X)]:
    E_phi = np.sum(final_results["b_jk"].T * final_results["estimated_density"] * final_results["delta_j"], axis=1)
    grad_f = f_x * (phi_x - E_phi)
    return grad_f

##############################################
# 5. Use the delta method to compute variance
##############################################

def compute_density_variance(x, final_results, cov_beta,smoothness_order=1):
    """
    Compute the approximate variance of the estimated density at x via the delta method.

    Given that
         f(x) = exp(θ₀ + φ(x)^Tβ) / Z,
    its gradient with respect to β is
         grad_f(x) = f(x) * [φ(x) - E[φ(X)]],
    so that
         Var(f(x)) ≈ grad_f(x)^T Cov(β̂) grad_f(x).

    Parameters:
    -----------
    x : float
        The evaluation point.
    final_results : dict
        Must contain the required keys.
    cov_beta : 2D numpy array
        Estimated covariance matrix of β̂.

    Returns:
    --------
    var_f : float, the estimated variance of f(x).
    """
    grad_f_val = compute_grad_f(x, final_results,smoothness_order=smoothness_order)
    var_f = np.dot(grad_f_val, np.dot(cov_beta, grad_f_val))
    return var_f

