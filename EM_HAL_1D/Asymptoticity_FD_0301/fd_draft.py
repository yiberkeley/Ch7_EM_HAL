# Helper function to create targeting basis /clever covariates
def create_cumulative_indicators_g(series, grid_points, prefix):
    """
    Create cumulative greater-or-equal indicators based on unequally spaced grid.

    Parameters:
    - series: pd.Series
    - grid_points: array-like, shape (K+1,)
    - prefix: str, prefix for indicator column names

    Returns:
    - indicators: pd.DataFrame
    """
    indicators_dict = {}
    id = 1
    for value in grid_points:
        id += 1
        indicator_col = f"{prefix}_g_{value:.4f}_{id}"
        indicators_dict[indicator_col] = (series > value).astype(int)
    indicators = pd.DataFrame(indicators_dict, index=series.index)

    return indicators

# Generate basis functions for data and evaluation grid
def create_targeting_basis_functions(data_long_train, grid_points, prefix='W1'):
    indicators = create_cumulative_indicators_g(data_long_train['W1'], grid_points, prefix=prefix)
    basis_df = pd.concat([indicators], axis=1)
    basis_tensor = torch.tensor(basis_df.values, dtype=torch.float32)
    return basis_tensor

# Targeting maximum likelihood

def targeting_M_step(targeting_points, uncensored_augmented, results, old_theta, norm_constraint=20):
    """
    This function performs an M-step update for a density model that has the form
       f(x) = exp(linear_predictor) / Z,
    where the linear predictor is the sum of two parts:
      (i) a “hal‐basis” part with an intercept and coefficients given by old_theta,
     (ii) a new “targeting‐basis” part with free coefficients (α) that are optimized.

    Only the targeting basis coefficients are updated; the intercept and the hal‐basis
    coefficients (old_theta) are kept fixed.

    Parameters
    ----------
    targeting_points : array-like
        The locations at which the targeting basis functions are defined.
    uncensored_augmented : DataFrame
        A pandas DataFrame containing the uncensored data points.
        (Note: weights are forced to be 1 for each observation in this version.)
    results : dict
        A dictionary containing (at least) the key "grid_points_hal_selected" with the
        hal design grid.
    old_theta : array-like
        The current (fixed) parameter vector for the intercept and hal basis functions.
        Here, old_theta[0] is the intercept and old_theta[1:] are the hal coefficients.
    norm_constraint : float, optional
        L1-norm constraint for the targeting coefficient(s) (default is 20).

    Returns
    -------
    updated_results : dict
        A dictionary with updated parameters and estimated density on a fine grid.
    """

    # ----------------------------
    # 1. Design matrix construction
    # ----------------------------
    start_time_m_design = time.time()

    # Use the hal grid from the previous iteration
    grid_points_hal_selected = results['grid_points_hal_selected']
    grid_points_hal = grid_points_hal_selected  # for hal-basis
    uncensored_data = uncensored_augmented

    # Create hal basis design matrix for uncensored data
    # (Assumes create_basis_functions returns a torch.Tensor)
    basis_tensor = create_basis_functions(uncensored_data, grid_points_hal)
    b_ik = basis_tensor.detach().numpy()  # shape: (n_data, n_hal_basis)

    # Create targeting basis design matrix for uncensored data
    basis_tensor_targeting = create_targeting_basis_functions(uncensored_data, targeting_points)
    b_ik_targeting = basis_tensor_targeting.numpy()  # shape: (n_data, n_targeting_basis)
    if b_ik_targeting.ndim == 1:
        b_ik_targeting = b_ik_targeting[:, None]

    # Create an evaluation grid (here 200 points) for computing the normalization constant.
    grid_eval = np.linspace(0, 1, 200)
    combined_grid = np.concatenate((grid_eval, grid_points_hal_selected))
    filtered_grid = combined_grid[combined_grid >= 0]
    filtered_grid = np.unique(filtered_grid)
    grid_eval = np.sort(filtered_grid)

    # Compute midpoints for integration
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})

    # Evaluate hal basis on the integration grid
    basis_grid_tensor = create_basis_functions(data_grid, grid_points_hal)
    b_jk = basis_grid_tensor.numpy()  # shape: (n_grid, n_hal_basis)

    # Evaluate targeting basis on the integration grid
    basis_grid_tensor_targeting = create_targeting_basis_functions(data_grid, targeting_points)
    b_jk_targeting = basis_grid_tensor_targeting.numpy()  # shape: (n_grid, n_targeting_basis)
    if b_jk_targeting.ndim == 1:
        b_jk_targeting = b_jk_targeting[:, None]

    end_time_m_design = time.time()
    m_step_time_design = end_time_m_design - start_time_m_design
    print(f"M-step Design Matrix Calculation time (sec): {m_step_time_design:.4f}")

    # ----------------------------
    # 2. Set up the optimization problem
    # ----------------------------
    start_time_m_optimize = time.time()

    # Compute the fixed (hal-basis) part of the linear predictor:
    #   fixed = intercept + (hal_basis dot old_hal_coefficients)
    # For uncensored data:
    fixed_data = old_theta[0] + np.dot(b_ik, old_theta[1:])
    # For the integration grid:
    fixed_grid = old_theta[0] + np.dot(b_jk, old_theta[1:])

    # --- Set weights to 1 by default ---
    weights_M = np.ones(len(uncensored_data))
    n_samples_weighted = np.sum(weights_M)

    # Compute the widths (delta) for integration and their logarithms
    delta_j = grid_eval[1:] - grid_eval[:-1]
    log_delta_j = np.log(delta_j)

    # The only free parameter is the targeting basis coefficient vector.
    # Its dimension is determined by the number of targeting basis functions.
    r = b_ik_targeting.shape[1]
    alpha = cp.Variable(r)

    # Define the full linear predictor by adding the targeting part:
    # For data points:
    L_data = fixed_data + b_ik_targeting @ alpha  # shape: (n_data,)
    # For grid points:
    L_grid = fixed_grid + b_jk_targeting @ alpha    # shape: (n_grid,)

    # Formulate the (negative) log-likelihood.
    # Data term:  -sum_i weights[i] * (fixed + targeting_effect)
    data_term = -cp.sum(cp.multiply(weights_M, L_data))
    # Normalization term:  n_samples_weighted * log_sum_exp( log(delta_j) + L_grid )
    norm_term = n_samples_weighted * cp.log_sum_exp(log_delta_j + L_grid)
    loss = data_term + norm_term

    # Optionally, we include a norm constraint on the targeting coefficients.
    constraints = [cp.norm1(alpha) <= norm_constraint]

    objective = cp.Minimize(loss)
    problem = cp.Problem(objective, constraints)

    # Warm start: initialize alpha (you may change this if you have a previous guess)
    alpha.value = np.zeros(r)

    # Solve the optimization problem (here using the ECOS solver)
    try:
        problem.solve(solver="ECOS")
    except Exception as e:
        print("ECOS solver failed in IPCW_HAL_init, falling back to SCS:", e)
        problem.solve(solver="SCS")

    end_time_m_optimize = time.time()
    m_step_time_optimize = end_time_m_optimize - start_time_m_optimize
    print(f"M-step CVXPY optimize time (sec): {m_step_time_optimize:.4f}")

    # ----------------------------
    # 3. Compute the estimated density on a fine grid
    # ----------------------------
    # Retrieve the optimized targeting coefficients
    theta_targeting = alpha.value

    # The fixed hal-basis parameters remain the same:
    theta_intercept = old_theta[0]
    theta_selected = old_theta[1:]

    # Now, evaluate the density on a fine grid (here 2000 points)
    grid_eval = np.linspace(0, 1, 2000)
    combined_grid = np.concatenate((grid_eval, grid_points_hal_selected))
    filtered_grid = combined_grid[combined_grid >= 0]
    filtered_grid = np.unique(filtered_grid)
    grid_eval_full = np.sort(filtered_grid)



    grid_midpoints_full = (grid_eval_full[:-1] + grid_eval_full[1:]) / 2
    data_grid_full = pd.DataFrame({'W1': grid_midpoints_full})

    # Evaluate hal basis on the fine grid
    basis_grid_tensor_full = create_basis_functions(data_grid_full, grid_points_hal)
    b_jk_full = basis_grid_tensor_full.numpy()

    # Evaluate targeting basis on the fine grid
    basis_grid_tensor_targeting_full = create_targeting_basis_functions(data_grid_full, targeting_points)
    b_jk_targeting_full = basis_grid_tensor_targeting_full.numpy()
    if b_jk_targeting_full.ndim == 1:
        b_jk_targeting_full = b_jk_targeting_full[:, None]

    delta_j_full = grid_eval_full[1:] - grid_eval_full[:-1]

    # The estimated log-density is the sum of the fixed (hal) part and the optimized targeting part.
    estimated_log_density = theta_intercept + b_jk_full @ theta_selected + b_jk_targeting_full @ theta_targeting
    estimated_density = np.exp(estimated_log_density)
    estimated_density /= np.sum(estimated_density * delta_j_full)  # Normalize so it integrates to 1

    # ----------------------------
    # 4. Package and return results
    # ----------------------------
    updated_results = {
        "old_theta": old_theta,               # fixed intercept and hal-basis coefficients
        "theta_targeting": theta_targeting,     # newly optimized targeting coefficients
        "theta_intercept": theta_intercept,
        "theta_selected": theta_selected,
        "estimated_density": estimated_density,
        "grid_midpoints": grid_midpoints_full,
        "grid_points_hal_selected": grid_points_hal_selected,
        "b_jk": b_jk_full,
        "b_jk_targeting": b_jk_targeting_full,
        "delta_j": delta_j_full,
        "grid_eval": grid_eval_full,
        "targeting_points": targeting_points
    }

    return updated_results

# Single Experiment Function
# ---------------------------
def run_single_experiment(seed, n_samples=1000,
                          evaluation_points=np.linspace(0.02, 0.98, 20),
                          candidate_lambdas=[55, 60, 65, 70],smoothness_order=1,ridge=1e-6,targeting_points=np.linspace(0.02, 0.98, 20)):
    """
    Run one experiment:
      - Simulate full (uncensored) data using a truncated normal.
      - Use 5-fold CV to select the best lambda.
      - Estimate density using first–order HAL NPMLE.
      - Compute the plug–in survival function.
      - Evaluate density on the evaluation grid (by interpolation).

    Returns a dictionary with:
      "estimated_density": density evaluated on evaluation_points,
      "survival": survival probabilities evaluated on the grid,
      "best_lambda": the best lambda chosen by CV,
      "evaluation_points": the evaluation grid.
    """
    np.random.seed(seed)
    T = generate_truncated_normal(n_samples)
    # For full data, we simply let W1 = T.
    data = pd.DataFrame({'W1': T})

    k = 5
    best_lambda, cv_risks = CV_full_HAL(data, k, candidate_lambdas, threshold=1e-4, n_jobs=1,smoothness_order=smoothness_order)

    init_res = estimate_density_npmle(data, threshold=1e-4, norm_constraint=best_lambda,smoothness_order=smoothness_order)

    # Evaluate density by linear interpolation on the midpoints.
    init_density_eval = np.interp(evaluation_points, init_res['grid_midpoints'], init_res['estimated_density'])

    # Compute survival function (using a step-function approximation)
    survival, grid_surv = compute_survival_from_density_full(init_res)
    init_surv_probs = np.interp(evaluation_points, grid_surv, survival, left=1.0, right=0.0)


    cov_beta = estimate_covariance_beta(data, init_res, ridge = ridge, smoothness_order=smoothness_order)
    ci_density_df = density_confidence_interval(evaluation_points, init_res, cov_beta, alpha=0.05,smoothness_order=smoothness_order)
    initial_density_se=ci_density_df['se']
    
    grid, grad_f_grid, delta = precompute_grad_f_grid(init_res, grid_size=1000,smoothness_order=smoothness_order)
    surv_ci_df = survival_confidence_interval_precomputed(evaluation_points, init_res, cov_beta, grid, grad_f_grid, delta, alpha=0.05)
    initial_survival_se=surv_ci_df['se']

    # Compute the standard error for the survival using the eic, 1(T> x) - E[1(T > X)]
    # Note: the standard error is computed as the sample standard deviation of the EIC divided by sqrt(n)
    # where n is the number of observations.
    EIC_matrix = np.zeros((data.shape[0], len(evaluation_points)))
    for i, x0 in enumerate(evaluation_points):
        EIC_matrix[:, i] = 1 * (data['W1'] > x0) - estimated_survival_at(x0, init_res)
    initial_survival_se_eic = np.std(EIC_matrix, axis=0, ddof=1) / np.sqrt(data.shape[0])
    


    ##Targeting
    targeted_fit = targeting_M_step(targeting_points=targeting_points,
                                    uncensored_augmented = data,
                                    results =init_res,
                                    old_theta = init_res.get("theta_value", None),
                                    norm_constraint=5*best_lambda)


    # Evaluate density by linear interpolation on the midpoints.
    final_density_eval = np.interp(evaluation_points, targeted_fit['grid_midpoints'], targeted_fit['estimated_density'])

    # Compute survival function after targeting (using a step-function approximation)
    survival, grid_surv = compute_survival_from_density_full(targeted_fit)
    final_surv_probs = np.interp(evaluation_points, grid_surv, survival, left=1.0, right=0.0)

    #Now, get the EIC matrix
    # Build the basis for the data
    basis_tensor = create_basis_functions(data, targeting_points,smoothness_order=0)
    b_ik_targeting = basis_tensor.numpy()
    survival_targeting=np.interp(targeting_points, grid_surv, survival, left=1.0, right=0.0)
    EIC_matrix=b_ik_targeting - survival_targeting
    final_survival_se = np.std(EIC_matrix, axis=0, ddof=1)/np.sqrt(EIC_matrix.shape[0])

    # Compute the standard error for the density estimates using the eic, 1(T> x) - E[1(T > X)]
    # Note: the standard error is computed as the sample standard deviation of the EIC divided by sqrt(n)
    # where n is the number of observations.
    EIC_matrix = np.zeros((data.shape[0], len(evaluation_points)))
    for i, x0 in enumerate(evaluation_points):
        EIC_matrix[:, i] = 1 * (data['W1'] > x0) - estimated_survival_at(x0, targeted_fit)
    final_survival_se_eic = np.std(EIC_matrix, axis=0, ddof=1) / np.sqrt(data.shape[0])

    return {
        "initial_density": init_density_eval,
        "final_density": final_density_eval,
        "initial_density_se": initial_density_se,
        "initial_survival": init_surv_probs,
        "final_survival": final_surv_probs,
        "initial_survival_se": initial_survival_se,
        "initial_survival_se_eic": initial_survival_se_eic,
        "final_survival_se": final_survival_se,
        "final_survival_se_eic": final_survival_se_eic,
        "best_lambda": best_lambda,
        "evaluation_points": evaluation_points,
        "cv_risks": cv_risks
    }

