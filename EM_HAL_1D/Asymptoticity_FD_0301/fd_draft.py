def estimate_density_npmle(data, threshold=1e-4, norm_constraint=3,smoothness_order=1):
    """
    Estimate density using a nonparametric MLE (NPMLE) with first–order HAL basis.

    Data is assumed complete with column 'W1'.

    Returns a dictionary with:
      - optimized_theta: CVXPY solution before pruning.
      - pruned_theta: theta after pruning small coefficients.
      - estimated_density: density evaluated on an evaluation grid.
      - grid_midpoints: midpoints of evaluation grid intervals.
      - grid_points_hal_selected: the knots (after pruning).
      - theta_selected: nonzero coefficients (excluding intercept).
      - b_jk: basis evaluated on the evaluation grid.
      - delta_j: interval widths.
      - grid_eval: evaluation grid endpoints.
    """
    n_samples = len(data)
    # Use all unique values in W1 as candidate knots; include 0 and 1.
    grid_points_hal = np.unique(np.concatenate(([0], data['W1'].values, [1])))

    #Knot points are selected as the percentiles.
    # Compute the number of percentiles as the nearest integer of 10*sqrt(n_samples)
    num_percentiles = int(np.rint(10 * np.sqrt(n_samples)))
    grid_points_hal = np.percentile(grid_points_hal, np.linspace(0, 100, num_percentiles))


    # Build the basis for the data
    basis_tensor = create_basis_functions(data, grid_points_hal,smoothness_order=smoothness_order)
    b_ik = basis_tensor.numpy()

    # Create an evaluation grid (e.g., 200 endpoints) and compute midpoints
    grid_eval = np.linspace(0, 1, 200)
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})
    basis_grid_tensor = create_basis_functions(data_grid, grid_points_hal,smoothness_order=smoothness_order)
    b_jk = basis_grid_tensor.numpy()

    K = len(grid_points_hal) + 1  # including intercept
    theta = cp.Variable(K)

    # Objective: - sum log f(W1) + n log Z
    first_term = -cp.sum(theta[0] + b_ik @ theta[1:])
    delta_j = grid_eval[1:] - grid_eval[:-1]
    log_delta_j = np.log(delta_j)
    log_density_grid = theta[0] + b_jk @ theta[1:]
    log_terms = log_delta_j + log_density_grid
    log_Z = cp.log_sum_exp(log_terms)
    second_term = n_samples * log_Z
    loss = first_term + second_term

    # Constrain L1–norm of coefficients (excluding intercept)
    constraints = [cp.norm1(theta[1:]) <= norm_constraint]
    prob = cp.Problem(cp.Minimize(loss), constraints)
    try:
        prob.solve(solver="ECOS")
    except Exception as e:
        print("ECOS solver failed: ", e, "\nUsing SCS instead.")
        prob.solve(solver="SCS")

    # Prune small coefficients
    theta_pruned = np.copy(theta.value)
    theta_pruned[1:] = np.where(np.abs(theta.value[1:]) > threshold, theta.value[1:], 0)
    non_zero_indices = np.nonzero(theta_pruned)[0]

    # Use the knots corresponding to nonzero coefficients (excluding intercept)
    grid_points_hal_selected = grid_points_hal[non_zero_indices[1:] - 1]

    # Augment the evaluation grid with the selected knots and re-sort
    grid_eval = np.sort(np.unique(np.concatenate((grid_eval, grid_points_hal_selected))))
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})
    basis_grid_tensor = create_basis_functions(data_grid, grid_points_hal,smoothness_order=smoothness_order)
    b_jk = basis_grid_tensor.numpy()
    delta_j = grid_eval[1:] - grid_eval[:-1]

    b_jk_pruned = b_jk[:, non_zero_indices[1:] - 1]
    theta_selected = theta_pruned[non_zero_indices[1:]]
    estimated_log_density = theta_pruned[0] + b_jk_pruned @ theta_selected
    estimated_density = np.exp(estimated_log_density)
    estimated_density /= np.sum(estimated_density * delta_j)
    theta_value = theta_pruned[non_zero_indices]

    return {
        "theta_value": theta_value,          # store entire vector for pruned theta including intercept
        "optimized_theta": theta.value,
        "pruned_theta": theta_pruned,
        "estimated_density": estimated_density,
        "grid_midpoints": grid_midpoints,
        "grid_points_hal_selected": grid_points_hal_selected,
        "theta_selected": theta_selected,
        "b_jk": b_jk_pruned,
        "delta_j": delta_j,
        "grid_eval": grid_eval
    }

