def split_data_k_folds(data, k):
    n = len(data)
    indices = np.arange(n)
    np.random.shuffle(indices)
    fold_size = n // k
    for i in range(k):
        test_indices = indices[i*fold_size:(i+1)*fold_size]
        train_indices = np.setdiff1d(indices, test_indices)
        yield data.iloc[train_indices].reset_index(drop=True), data.iloc[test_indices].reset_index(drop=True)

