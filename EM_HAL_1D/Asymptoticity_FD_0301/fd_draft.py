def create_cumulative_indicators_ge(series, grid_points, prefix):
    """
    For each grid point g, return an indicator function 1{series >= g}.
    """
    indicators_dict = {}
    counter = 1
    for g in grid_points:
        counter += 1
        colname = f"{prefix}_ge_{g:.4f}_{counter}"
        indicators_dict[colname] = (series >= g).astype(int)
    return pd.DataFrame(indicators_dict, index=series.index)

def create_basis_functions(data, grid_points, prefix='W1',smoothness_order=1):
    """
    Create first–order basis functions defined as (x-g)_+ = max(0, x-g)
    by combining the cumulative indicator with a linear shift.
    Returns a torch tensor.
    """
    if smoothness_order == 1:
      # For each knot g, define basis function = 1{x >= g}*(x - g)
      basis_cols = []
      for g in grid_points:
          basis_col = np.where(data[prefix] >= g, data[prefix] - g, 0)
          basis_cols.append(basis_col)
      basis_array = np.array(basis_cols).T  # shape: (n_samples, K)
      return torch.tensor(basis_array, dtype=torch.float32)
    elif smoothness_order == 0:
      indicators = create_cumulative_indicators_ge(data[prefix], grid_points, prefix=prefix)
      # You could combine with other features if needed.
      basis_df = pd.concat([indicators], axis=1)
      return torch.tensor(basis_df.values, dtype=torch.float32)
    else:
        raise ValueError("order must be 0 (zero–order) or 1 (first–order).")


