from scipy.integrate import cumulative_trapezoid

def compute_survival_from_density_full(estimator_dict, grid_eval=None):
    """
    Compute the survival function S(t)=1-CDF(t) from the estimated density for a first–order HAL estimator.

    This function uses the trapezoidal rule to integrate the (smooth) estimated density.
    It returns the survival function evaluated on the grid_eval endpoints.

    Parameters
    ----------
    estimator_dict : dict
        Output from the first–order HAL estimator (e.g., estimate_density_npmle adapted for first–order HAL).
        Must contain:
            - 'estimated_density': the estimated density evaluated on grid_midpoints.
            - 'grid_midpoints': the midpoints of the evaluation grid where density is evaluated.
    grid_eval : array-like, optional
        The evaluation grid endpoints over [0,1]. If not provided, defaults to
        estimator_dict['grid_eval'] if available or np.linspace(0, 1, 1000).

    Returns
    -------
    survival : np.ndarray
        The survival function evaluated on grid_eval.
    grid_eval : np.ndarray
        The evaluation grid used.
    """
    if grid_eval is None:
        grid_eval = estimator_dict.get('grid_eval', np.linspace(0, 1, 1000))
    # Here, we assume the density is estimated at grid_midpoints.
    grid_mid = estimator_dict['grid_midpoints']
    density = estimator_dict['estimated_density']
    # To evaluate the CDF on the grid_eval, interpolate the estimated density to grid_eval.
    # This yields an array of the same length as grid_eval.
    density_on_eval = np.interp(grid_eval, grid_mid, density, left=density[0], right=density[-1])
    # Use cumtrapz with initial=0 to compute the cumulative integral (CDF)
    cdf = cumulative_trapezoid(density_on_eval, grid_eval, initial=0)
    # Normalize the CDF (to be exactly 1 at the right end)
    cdf /= cdf[-1]
    survival = 1 - cdf
    return survival, grid_eval



