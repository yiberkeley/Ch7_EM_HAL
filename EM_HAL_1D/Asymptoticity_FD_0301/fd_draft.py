# 6. Construct confidence intervals for a grid of x's
##############################################

def density_confidence_interval(x_values, final_results, cov_beta, alpha=0.05,smoothness_order=1):
    """
    For each evaluation point in x_values, compute the estimated density,
    its standard error (via the delta method), and the (1-α)% confidence interval.

    Parameters:
    -----------
    x_values : array-like
        Points at which to compute the inference.
    final_results : dict
        The NPMLE result from the full data estimation.
    cov_beta : 2D numpy array
        Estimated covariance matrix of β̂.
    alpha : float
        Significance level (default 0.05 for 95% CIs).

    Returns:
    --------
    results_df : DataFrame with columns:
         'x'       : evaluation point,
         'density' : estimated density f(x),
         'se'      : standard error,
         'lower'   : lower CI bound,
         'upper'   : upper CI bound.
    """
    z = norm.ppf(1 - alpha / 2)
    results = []
    for x in x_values:
        f_x = estimated_density_at(x, final_results)
        var_f = compute_density_variance(x, final_results, cov_beta,smoothness_order=smoothness_order)
        se = np.sqrt(var_f)
        lower = f_x - z * se
        upper = f_x + z * se
        results.append({'x': x, 'density': f_x, 'se': se, 'lower': lower, 'upper': upper})
    return pd.DataFrame(results)

