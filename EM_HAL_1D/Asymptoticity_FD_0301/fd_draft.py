def compute_individual_score(row, final_results,smoothness_order=1):
    """
    For full data (i.e. no censoring), compute the score contribution for a single observation.

    The score is given by:
        s_i = φ(W1_i) - E[φ(X)],
    where the expectation is computed over the integration grid using the estimated density.

    Parameters:
    -----------
    row : Series
        A row from the full data containing at least the column "W1".
    final_results : dict
        Dictionary from your NPMLE that includes:
          - "grid_midpoints": 1D array of grid midpoints used for integration.
          - "estimated_density": estimated density on those midpoints.
          - "delta_j": grid interval lengths.
          - "grid_points_hal_selected": the selected HAL knots.
          - "b_jk": basis functions evaluated on the integration grid (each row corresponds to a grid point).

    Returns:
    --------
    score : 1D numpy array (length = number of selected basis functions)
    """
    # For full data, we use the value in "W1"
    W1 = row['W1']
    # Compute the expectation E[φ(X)] on the grid:
    E_phi = np.sum(final_results["b_jk"].T * final_results["estimated_density"] * final_results["delta_j"], axis=1)
    # Evaluate the basis at the observation:
    df_W1 = pd.DataFrame({'W1': [W1]})
    phi_W1 = create_basis_functions(df_W1, final_results["grid_points_hal_selected"],smoothness_order=smoothness_order).numpy().flatten()
    score = phi_W1 - E_phi
    return score

##############################################
# 2. Estimate the covariance matrix of β̂
##############################################

def estimate_covariance_beta(data, final_results,ridge=1e-6, smoothness_order=1):
    """
    Estimate the covariance matrix of the (non-intercept) coefficients β̂.

    Here we form the individual score vectors (one per observation) and then estimate
    the Fisher information as the average outer product:

         Î = (1/n) ∑ s_i s_i^T,

    and finally use (asymptotically)

         Cov(β̂) ≈ Î⁻¹ / n.

    Parameters:
    -----------
    data : DataFrame
        The full data with column "W1".
    final_results : dict
        The NPMLE result (from estimate_density_npmle) containing the necessary keys.

    Returns:
    --------
    cov_beta : 2D numpy array of shape (p, p), where p = number of selected basis functions.
    """
    scores = []
    for _, row in data.iterrows():
        s = compute_individual_score(row, final_results,smoothness_order=smoothness_order)
        scores.append(s)
    scores = np.array(scores)  # shape: (n, p)
    n = scores.shape[0]

    # Estimate the expected outer product: Î = (1/n)*∑ s_i s_i^T.
    I_hat = np.dot(scores.T, scores) / n
    I_hat_reg = I_hat + (ridge/np.sqrt(I_hat.shape[0]))  * np.eye(I_hat.shape[0])
    try:
        cov_beta = np.linalg.inv(I_hat_reg) / n
    except np.linalg.LinAlgError:
        cov_beta = np.linalg.pinv(I_hat_reg) / n
    return cov_beta


