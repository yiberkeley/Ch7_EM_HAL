def compute_total_log_likelihood_full(data, results):
    """
    Compute the total log-likelihood for full (uncensored) data.
    Data is assumed to have column 'W1'.
    """
    estimated_density = results['estimated_density']
    grid_midpoints = results['grid_midpoints']
    density_interp = interp1d(grid_midpoints, estimated_density, kind='linear',
                               bounds_error=False, fill_value=(estimated_density[0], estimated_density[-1]))
    x = data['W1'].values
    return np.sum(np.log(density_interp(x)))

