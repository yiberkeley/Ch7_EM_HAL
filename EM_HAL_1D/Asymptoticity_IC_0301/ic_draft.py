def compute_individual_score_interval(row, final_results):
    """
    For interval-censored data, compute the score contribution for one observation.

    The score is defined as:
         s_i = E[φ(X) | L_i ≤ X ≤ R_i] - E[φ(X)],
    where the full expectation E[φ(X)] is computed over the entire integration grid,
    and the conditional expectation is computed using only the grid points in [L_i, R_i].

    Parameters:
      row : a row from the data DataFrame (must contain 'L' and 'R')
      final_results : dict, output from your HAL estimation (e.g. interval_gradient_HAL_init)
                      that contains:
                          - "grid_midpoints": 1D numpy array of integration grid midpoints,
                          - "estimated_density": estimated density at these midpoints,
                          - "delta_j": grid interval widths,
                          - "grid_points_hal_selected": the selected knots,
                          - "b_jk": basis functions evaluated on the integration grid.

    Returns:
      score : 1D numpy array (length = number of selected basis functions)
    """
    L = row['L']
    R = row['R']
    # Full expectation of the basis functions:
    E_phi = np.sum(final_results["b_jk"].T * final_results["estimated_density"] * final_results["delta_j"], axis=1)

    # Find grid points within the interval [L, R]
    grid = final_results["grid_midpoints"]
    mask = (grid >= L) & (grid <= R)

    if np.sum(mask) == 0:
        # If no grid points fall into [L, R], we fall back to E_phi.
        cond_exp = E_phi
    else:
        num = np.sum(final_results["b_jk"][mask].T * final_results["estimated_density"][mask] * final_results["delta_j"][mask], axis=1)
        den = np.sum(final_results["estimated_density"][mask] * final_results["delta_j"][mask])
        cond_exp = num / den

    return cond_exp - E_phi

##############################################
# 2. Estimate the covariance matrix of β̂ (Interval-Censored)
##############################################

def estimate_covariance_beta_interval(data, final_results, ridge=1e-6, smoothness_order=1):
    """
    NOTE: THE SMOOTHNESS_ORDER IS ONLY FOR CONVENIENCE AND NOT USED HERE
    Estimate the asymptotic covariance matrix of the non-intercept coefficients β̂
    for interval-censored data by computing the individual score vectors and then
    forming the (inverse) Fisher information.

    That is, if s_i is the score for observation i then define
         I_hat = (1/n) ∑ s_i s_i^T,
    and approximate
         Cov(β̂) ≈ I_hat⁻¹ / n.

    Parameters:
      data : DataFrame with columns 'L' and 'R'
      final_results : dict, output from your HAL estimation (e.g., interval_gradient_HAL_init)

    Returns:
      cov_beta : 2D numpy array (p x p), where p is the number of selected basis functions.
    """
    scores = []
    for _, row in data.iterrows():
        s = compute_individual_score_interval(row, final_results)
        scores.append(s)
    scores = np.array(scores)  # shape (n, p)
    n = scores.shape[0]


    # Form the Fisher information matrix estimate
    I_hat = np.dot(scores.T, scores) / n
    # Add the ridge (regularization) term
    I_hat_reg = I_hat + (ridge/np.sqrt(I_hat.shape[0]))  * np.eye(I_hat.shape[0])  

    try:
        cov_beta = np.linalg.inv(I_hat_reg) / n
    except np.linalg.LinAlgError:
        cov_beta = np.linalg.pinv(I_hat_reg) / n
    return cov_beta

##############################################
# 3. Estimate the density at an arbitrary x
##############################################

def estimated_density_at(x, final_results):
    """
    For any x in [0,1] (or the region of interest), return the estimated density.
    This is done via linear interpolation on the grid midpoints.

    Parameters:
      x : float or array-like, evaluation point(s)
      final_results : dict, must contain "grid_midpoints" and "estimated_density"

    Returns:
      f_x : float or array of density values
    """
    f_interp = interp1d(final_results["grid_midpoints"], final_results["estimated_density"],
                        kind="linear", bounds_error=False, fill_value="extrapolate")
    return f_interp(x)

##############################################
# 4. Compute the gradient of the density
##############################################

def compute_grad_f(x, final_results,smoothness_order):
    """
    Compute the gradient of the estimated density at x with respect to the non-intercept
    coefficients. For interval-censored data the gradient is still defined as
         grad_f(x) = f(x) * [φ(x) - E[φ(X)]],
    where E[φ(X)] is computed over the integration grid.

    Parameters:
      x : float, the evaluation point
      final_results : dict, must contain:
                    - "grid_points_hal_selected": selected HAL knots,
                    - "b_jk": basis functions evaluated on the integration grid,
                    - "estimated_density": estimated density on the grid,
                    - "delta_j": grid interval widths.

    Returns:
      grad_f : 1D numpy array (gradient vector)
    """
    # Get density at x
    f_x = estimated_density_at(x, final_results)

    # Evaluate basis functions at x
    df_x = pd.DataFrame({'W1': [x]})
    phi_x = create_basis_functions(df_x, final_results["grid_points_hal_selected"],smoothness_order=smoothness_order).numpy().flatten()

    # Full expectation of basis functions over the grid:
    E_phi = np.sum(final_results["b_jk"].T * final_results["estimated_density"] * final_results["delta_j"], axis=1)

    return f_x * (phi_x - E_phi)

##############################################
# 5. Compute density variance via the delta method
##############################################

def compute_density_variance(x, final_results, cov_beta,smoothness_order):
    """
    Compute the approximate variance of the estimated density at x using the delta method.

    That is, if
         f(x) = exp(θ₀ + φ(x)^Tβ) / Z,
    then its gradient with respect to β is
         grad_f(x) = f(x) [φ(x) - E[φ(X)]],
    and hence
         Var(f(x)) ≈ grad_f(x)^T · Cov(β̂) · grad_f(x).

    Parameters:
      x : float, the evaluation point
      final_results : dict, contains necessary quantities
      cov_beta : 2D numpy array, covariance matrix of β̂

    Returns:
      var_f : float, the approximate variance of f(x)
    """
    grad = compute_grad_f(x, final_results,smoothness_order=smoothness_order)
    return np.dot(grad, np.dot(cov_beta, grad))

##############################################
# 6. Construct Confidence Intervals for Density
##############################################

def density_confidence_interval(x_values, final_results, cov_beta, alpha=0.05,smoothness_order=1):
    """
    For each evaluation point in x_values, compute the estimated density,
    its standard error (via the delta method), and then construct a (1-α)% confidence interval.

    Parameters:
      x_values : array-like of evaluation points
      final_results : dict, output from your interval-censored HAL estimation
      cov_beta : 2D numpy array, estimated covariance matrix of β̂
      alpha : float, significance level (default 0.05 for 95% CI)

    Returns:
      results_df : DataFrame with columns 'x', 'density', 'se', 'lower', and 'upper'
    """
    z = norm.ppf(1 - alpha/2)
    results = []
    for x in x_values:
        f_x = estimated_density_at(x, final_results)
        var_f = compute_density_variance(x, final_results, cov_beta,smoothness_order=smoothness_order)
        se = np.sqrt(var_f)
        lower = f_x - z * se
        upper = f_x + z * se
        results.append({'x': x, 'density': f_x, 'se': se, 'lower': lower, 'upper': upper})
    return pd.DataFrame(results)

##############################################
# Precompute the Density Gradient on a Fine Uniform Grid
##############################################

def precompute_grad_f_grid(final_results, grid_size=1000,smoothness_order=1):
    """
    Precompute the gradient of the estimated density f(x) on a uniform grid over [0,1].

    Parameters:
      final_results : dict, the HAL estimation result (contains keys used in compute_grad_f)
      grid_size : int, number of points in the uniform grid (default: 1000)

    Returns:
      grid : numpy array of shape (grid_size,), the uniform grid points over [0,1]
      grad_f_grid : numpy array of shape (grid_size, p), where p is the number of non-intercept coefficients,
                    containing grad_f(x) at each grid point.
      delta : float, the uniform grid spacing.
    """
    grid = np.linspace(0, 1, grid_size)
    grad_f_list = []
    for x in grid:
        grad_f_list.append(compute_grad_f(x, final_results,smoothness_order=smoothness_order))
    grad_f_grid = np.array(grad_f_list)  # shape: (grid_size, p)
    delta = grid[1] - grid[0]
    return grid, grad_f_grid, delta

##############################################
# Compute the Survival Gradient Using the Precomputed Grid
##############################################

def compute_grad_S_from_precomputed(x0, grid, grad_f_grid, delta):
    """
    Given a precomputed uniform grid and corresponding grad_f values,
    compute the survival gradient:
         ∇_β S(x0) = ∫_{x0}^1 ∇_β f(y) dy,
    by summing the precomputed gradients for grid points >= x0.

    Parameters:
      x0 : float, evaluation point.
      grid : numpy array, the precomputed uniform grid over [0,1].
      grad_f_grid : numpy array, precomputed gradient values at each grid point.
      delta : float, uniform grid spacing.

    Returns:
      grad_S : 1D numpy array, the approximate gradient vector of S(x0).
    """
    mask = grid >= x0
    grad_S = np.sum(grad_f_grid[mask], axis=0) * delta
    return grad_S

##############################################
# Survival Function and Variance via Delta Method
##############################################

def estimated_survival_at(x0, final_results):
    """
    Estimate the survival function S(x0) = ∫_{x0}^1 f(y) dy using a Riemann sum
    on the original integration grid.
    """
    grid = final_results["grid_midpoints"]
    f = final_results["estimated_density"]
    delta = final_results["delta_j"]
    mask = grid >= x0
    return np.sum(f[mask] * delta[mask])

def compute_survival_variance_precomputed(x0, final_results, cov_beta, grid, grad_f_grid, delta):
    """
    Compute the approximate variance of the survival function S(x0) using the precomputed
    survival gradient and the delta method.

    Var(S(x0)) ≈ (∇_β S(x0))ᵀ · Cov(β) · (∇_β S(x0))
    """
    grad_S = compute_grad_S_from_precomputed(x0, grid, grad_f_grid, delta)
    return np.dot(grad_S, np.dot(cov_beta, grad_S))

def survival_confidence_interval_precomputed(x_values, final_results, cov_beta, grid, grad_f_grid, delta, alpha=0.05):
    """
    For each evaluation point x0 in x_values, compute the survival function S(x0)
    and its (1-α)% confidence interval using the delta method with precomputed gradients.
    """
    z = norm.ppf(1 - alpha/2)
    results = []
    for x0 in x_values:
        S_x0 = estimated_survival_at(x0, final_results)
        var_S = compute_survival_variance_precomputed(x0, final_results, cov_beta, grid, grad_f_grid, delta)
        se = np.sqrt(np.maximum(var_S, 0))
        lower = S_x0 - z * se
        upper = S_x0 + z * se
        results.append({'x': x0, 'survival': S_x0, 'se': se, 'lower': lower, 'upper': upper})
    return pd.DataFrame(results)

def run_single_experiment(seed, n_samples=1000, n_intervals=5,
                          evaluation_points=np.linspace(0, 1, 100),
                          candidate_lambdas=[55, 60, 65, 70],
                          smoothness_order=1,
                          ridge=0):
    """
    Runs one experiment:
      - Generates data and performs uniform imputation.
      - Performs CV (using candidate lambdas around 60) to select the best lambda.
      - Computes an initial density estimate via first–order HAL.
      - Refines the estimate via the EM algorithm.
      - Evaluates both the initial and final estimates for density and survival probabilities at evaluation_points.
    Returns a dictionary with:
      "initial_density": 1D array (len(evaluation_points)) from initial HAL,
      "final_density": 1D array from the EM refinement,
      "initial_survival": 1D array of plug–in survival (initial),
      "final_survival": 1D array of plug–in survival (final),
      "best_lambda": the selected lambda,
      "evaluation_points": the evaluation grid.
    """
    np.random.seed(seed)
    T = generate_truncated_normal(n_samples)
    intervals = generate_inspection_intervals(n_samples, n_intervals)
    data = convert_to_interval_censored_data(T, intervals)
    data = uniform_imputation(data)

    k = 5
    best_lambda, cv_risks = CV_interval_HAL(data, k, candidate_lambdas, threshold=1e-4, n_jobs=1,smoothness_order=smoothness_order)

    initial_results = interval_gradient_HAL_init(data, threshold=1e-4, norm_constraint=best_lambda,smoothness_order=smoothness_order)
    final_results, _ = EM_HAL_algorithm(data, initial_results, tolerance=0.05, max_iterations=100, num_samples=200,\
                                        norm_constraint=best_lambda*5,smoothness_order=smoothness_order)

    # Evaluate initial and final density estimates (linear interpolation)
    initial_density = np.interp(evaluation_points, initial_results["grid_midpoints"], initial_results["estimated_density"])
    final_density = np.interp(evaluation_points, final_results["grid_midpoints"], final_results["estimated_density"])

    # Evaluate plug–in survival probabilities
    initial_survival = compute_survival_probabilities(initial_results, evaluation_points,smoothness_order=smoothness_order)
    final_survival = compute_survival_probabilities(final_results, evaluation_points,smoothness_order=smoothness_order)


    cov_beta = estimate_covariance_beta_interval(data, initial_results, ridge = ridge,smoothness_order=smoothness_order)
    ci_density_df = density_confidence_interval(evaluation_points, initial_results, cov_beta, alpha=0.05,smoothness_order=smoothness_order)
    initial_density_se=ci_density_df['se']
    grid, grad_f_grid, delta = precompute_grad_f_grid(initial_results, grid_size=1000,smoothness_order=smoothness_order)
    surv_ci_df = survival_confidence_interval_precomputed(evaluation_points, initial_results, cov_beta, grid, grad_f_grid, delta, alpha=0.05)
    initial_survival_se=surv_ci_df['se']

    cov_beta = estimate_covariance_beta_interval(data, final_results, ridge = ridge,smoothness_order=smoothness_order)
    ci_density_df = density_confidence_interval(evaluation_points, final_results, cov_beta, alpha=0.05,smoothness_order=smoothness_order)
    final_density_se=ci_density_df['se']
    grid, grad_f_grid, delta = precompute_grad_f_grid(final_results, grid_size=1000,smoothness_order=smoothness_order)
    surv_ci_df = survival_confidence_interval_precomputed(evaluation_points, final_results, cov_beta, grid, grad_f_grid, delta, alpha=0.05)
    final_survival_se=surv_ci_df['se']

    return {
            "initial_density": initial_density,
            "final_density": final_density,
            "initial_density_se": initial_density_se,
            "final_density_se": final_density_se,
            "initial_survival": initial_survival,
            "final_survival": final_survival,
            "initial_survival_se": initial_survival_se,
            "final_survival_se": final_survival_se,
            "best_lambda": best_lambda,
            "evaluation_points": evaluation_points,
            "cv_risks": cv_risks
    }



def run_multiple_experiments(n_experiments=3, n_samples=1000, n_intervals=5,
                                      evaluation_points=np.linspace(0.02, 0.98, 20),
                                      candidate_lambdas=[55, 60, 65, 70],
                                      n_jobs=-1,
                                      smoothness_order=1,
                                      ridge=0):
    """
    Runs multiple experiments in parallel and returns:
      - initial_density_df: DataFrame (rows: evaluation points, columns: experiments) for initial density.
      - final_density_df: DataFrame for final density.
      - initial_survival_df: DataFrame for initial survival.
      - final_survival_df: DataFrame for final survival.
      - best_lambda_df: DataFrame with one row per experiment for the selected best lambda.
    """
    seeds = [12776 + i for i in range(n_experiments)]
    experiment_func = partial(run_single_experiment, n_samples=n_samples, n_intervals=n_intervals,
                                evaluation_points=evaluation_points, candidate_lambdas=candidate_lambdas,smoothness_order=smoothness_order,ridge=ridge)
    with Pool(processes=n_jobs if n_jobs != -1 else None) as pool:
        results = pool.map(experiment_func, seeds)

    # Extract arrays for each estimator
    initial_density_arr = np.column_stack([res["initial_density"] for res in results])
    final_density_arr = np.column_stack([res["final_density"] for res in results])
    initial_survival_arr = np.column_stack([res["initial_survival"] for res in results])
    final_survival_arr = np.column_stack([res["final_survival"] for res in results])

    initial_density_se_arr = np.column_stack([res["initial_density_se"] for res in results])
    final_density_se_arr = np.column_stack([res["final_density_se"] for res in results])
    initial_survival_se_arr = np.column_stack([res["initial_survival_se"] for res in results])
    final_survival_se_arr = np.column_stack([res["final_survival_se"] for res in results])

    experiments = [f"Exp_{i+1}" for i in range(n_experiments)]

    initial_density_df = pd.DataFrame(initial_density_arr, index=evaluation_points, columns=experiments)
    final_density_df = pd.DataFrame(final_density_arr, index=evaluation_points, columns=experiments)
    initial_survival_df = pd.DataFrame(initial_survival_arr, index=evaluation_points, columns=experiments)
    final_survival_df = pd.DataFrame(final_survival_arr, index=evaluation_points, columns=experiments)

    initial_density_df_se = pd.DataFrame(initial_density_se_arr, index=evaluation_points, columns=experiments)
    final_density_df_se = pd.DataFrame(final_density_se_arr, index=evaluation_points, columns=experiments)
    initial_survival_df_se = pd.DataFrame(initial_survival_se_arr, index=evaluation_points, columns=experiments)
    final_survival_df_se = pd.DataFrame(final_survival_se_arr, index=evaluation_points, columns=experiments)

    best_lambda_df = pd.DataFrame({
        "Experiment": experiments,
        "Best_Lambda": [res["best_lambda"] for res in results]
    })




    return  initial_density_df, final_density_df, initial_survival_df, final_survival_df,initial_density_df_se,final_density_df_se, initial_survival_df_se, final_survival_df_se, best_lambda_df

