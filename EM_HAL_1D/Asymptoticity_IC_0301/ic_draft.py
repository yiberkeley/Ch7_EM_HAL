def CV_interval_HAL(data, k, lambda_values, threshold=1e-4, n_jobs=-1,smoothness_order=1):
    """
    Perform k-fold cross-validation for HAL across candidate lambda values.
    When n_jobs==1, run serially to avoid nested pools.
    Returns the best lambda and a dictionary of mean validation risks.
    """
    args = [(lamb, data, k, threshold,smoothness_order) for lamb in lambda_values]
    if n_jobs == 1:
        results = [compute_validation_risk_for_lambda(arg) for arg in args]
    else:
        with Pool(processes=n_jobs if n_jobs != -1 else None) as pool:
            results = pool.map(compute_validation_risk_for_lambda, args)
    mean_validation_risks = dict(results)
    best_lambda = max(mean_validation_risks, key=mean_validation_risks.get)
    return best_lambda, mean_validation_risks

