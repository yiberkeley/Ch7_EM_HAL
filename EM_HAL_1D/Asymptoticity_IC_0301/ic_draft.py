def compute_survival_from_density(estimator_dict, smoothness_order=1, grid_eval=None):
    """
    Compute the survival function from the estimated density in a numerically stable manner
    using the trapezoidal rule.
    """
    if grid_eval is None:
        grid_eval = estimator_dict.get('grid_eval', np.linspace(0, 1, 1000))

    # Create the design matrix on the evaluation grid
    data_grid = pd.DataFrame({'W1': grid_eval})
    knots = estimator_dict['grid_points_hal_selected']
    basis_tensor = create_basis_functions(data_grid, knots, smoothness_order)
    b_jk = basis_tensor.numpy()

    # Get parameters (with fallbacks)
    theta_intercept = estimator_dict.get('theta_intercept', estimator_dict['theta_value'][0])
    theta_selected = estimator_dict.get('theta_selected', estimator_dict['theta_value'][1:])

    # Compute log-density and then stabilize by subtracting the maximum
    log_density = theta_intercept + b_jk @ theta_selected
    log_density_stable = log_density - np.max(log_density)
    density = np.exp(log_density_stable)

    # Normalize density using the trapezoidal rule
    delta = np.diff(grid_eval)
    integral = np.trapz(density, grid_eval)
    if integral <= 0:
        raise ValueError("Total integral of the density is non-positive.")
    density /= integral

    # Compute the cumulative distribution function (CDF) using the trapezoidal rule
    cdf = np.cumsum((density[:-1] + density[1:]) / 2 * delta)
    cdf = np.insert(cdf, 0, 0)  # start at 0
    cdf /= cdf[-1]  # ensure the CDF ends at 1

    survival = 1 - cdf
    return survival, grid_eval


def compute_survival_probabilities(estimator_dict, evaluation_points, grid_eval=None,smoothness_order=1):
    survival, grid_eval = compute_survival_from_density(estimator_dict, grid_eval=grid_eval,smoothness_order=smoothness_order)
    survival_probs = np.interp(evaluation_points, grid_eval, survival, left=1.0, right=0.0)
    return survival_probs

