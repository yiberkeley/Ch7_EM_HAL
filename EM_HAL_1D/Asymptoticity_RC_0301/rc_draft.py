def create_cumulative_indicators_ge(series, grid_points, prefix):
    indicators_dict = {}
    counter = 1
    for value in grid_points:
        counter += 1
        indicator_col = f"{prefix}_ge_{value:.4f}_{counter}"
        indicators_dict[indicator_col] = (series >= value).astype(int)
    return pd.DataFrame(indicators_dict, index=series.index)


def create_basis_functions(data, grid_points, smoothness_order=1,prefix='W1'):
    """
    Create first-order basis functions defined as (x - g)_+ = max(0, x - g)
    for each knot g in grid_points. Returns a torch tensor.
    """
    if smoothness_order == 0:
        # Zero–order HAL: use cumulative indicator functions.
        indicators = create_cumulative_indicators_ge(data[prefix], grid_points, prefix)
        basis_df = pd.concat([indicators], axis=1)
        return torch.tensor(basis_df.values, dtype=torch.float32)
    elif smoothness_order == 1:
        # First–order HAL: use ramp functions (x - g)_+.
        basis_cols = []
        for g in grid_points:
            # (x - g)_+ = max(0, x - g)
            basis_col = np.maximum(data[prefix].values - g, 0)
            basis_cols.append(basis_col)
        basis_array = np.array(basis_cols).T  # shape: (n_samples, number of knots)
        return torch.tensor(basis_array, dtype=torch.float32)
    else:
        raise ValueError("order must be 0 (zero–order) or 1 (first–order).")


def IPCW_HAL_init(data, threshold=1e-4, norm_constraint=3,smoothness_order=1):
    """
    First–order HAL estimator for the density from right–censored data using inverse probability censoring weights.
    Basis functions are (x - g)_+.
    Returns a dictionary with estimated parameters and evaluation grid.
    """
    # Fit a Kaplan–Meier model on the censoring process (1-delta)
    kmf = KaplanMeierFitter()
    kmf.fit(durations=data['T_tilde'], event_observed=1 - data['delta'])

    # Restrict to uncensored data
    uncensored = data[data['delta'] == 1].copy()
    uncensored['W1'] = uncensored['T_tilde']
    uncensored['ipcw_weight'] = uncensored['T_tilde'].apply(lambda t: 1 / kmf.survival_function_at_times(t).values[0])

    # Define knots from uncensored event times plus boundaries 0 and 1.
    grid_points_hal = np.unique(np.concatenate(([0], uncensored['W1'].values, [1])))


    #Knot points are selected as the percentiles.
    # Compute the number of percentiles as the nearest integer of 10*sqrt(n_samples)
    num_percentiles = int(np.rint(10 * np.sqrt(len(data))))
    grid_points_hal = np.percentile(grid_points_hal, np.linspace(0, 100, num_percentiles))

    # Compute basis for the uncensored data
    basis_tensor = create_basis_functions(uncensored, grid_points_hal,smoothness_order)
    b_ik = basis_tensor.numpy()

    # Create an integration grid for normalization
    grid_eval = np.linspace(0, 1, 200)
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})
    basis_grid_tensor = create_basis_functions(data_grid, grid_points_hal,smoothness_order)
    b_jk = basis_grid_tensor.numpy()

    K = len(grid_points_hal) + 1  # intercept plus basis functions
    theta = cp.Variable(K)

    weights = uncensored['ipcw_weight'].values
    n_weighted = np.sum(weights)

    first_term = -cp.sum((theta[0] + b_ik @ theta[1:]) @ weights)
    delta_j = grid_eval[1:] - grid_eval[:-1]
    log_delta_j = np.log(delta_j)
    log_density_grid = theta[0] + b_jk @ theta[1:]
    log_terms = log_delta_j + log_density_grid
    log_Z = cp.log_sum_exp(log_terms)
    second_term = n_weighted * log_Z
    loss = first_term + second_term
    constraints = [cp.norm1(theta) <= norm_constraint]
    problem = cp.Problem(cp.Minimize(loss), constraints)

    try:
        problem.solve(solver="ECOS")
    except Exception as e:
        print("ECOS solver failed in IPCW_HAL_init, falling back to SCS:", e)
        problem.solve(solver="SCS")

    # Prune small coefficients
    theta_pruned = np.copy(theta.value)
    theta_pruned[1:] = np.where(np.abs(theta.value[1:]) > threshold, theta.value[1:], 0)
    non_zero = np.nonzero(theta_pruned)[0]

    # Select knots corresponding to nonzero coefficients (excluding intercept)
    grid_points_hal_selected = grid_points_hal[non_zero[1:] - 1]

    # Re-evaluate the density on a fine grid
    grid_eval = np.linspace(0, 1, 1000)
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})
    basis_grid_tensor = create_basis_functions(data_grid, grid_points_hal,smoothness_order)
    b_jk = basis_grid_tensor.numpy()
    delta_j = grid_eval[1:] - grid_eval[:-1]

    b_jk_pruned = b_jk[:, non_zero[1:] - 1]
    theta_selected = theta_pruned[non_zero[1:]]
    theta_intercept = theta_pruned[0]

    estimated_log_density = theta_pruned[0] + b_jk_pruned @ theta_selected
    estimated_density = np.exp(estimated_log_density)
    estimated_density /= np.sum(estimated_density * delta_j)

    theta_value = theta_pruned[non_zero]
    return {
        "theta_value": theta_value,
        "optimized_theta": theta.value,
        "pruned_theta": theta_pruned,
        "theta_intercept": theta_intercept,
        "estimated_density": estimated_density,
        "grid_midpoints": grid_midpoints,
        "grid_points_hal_selected": grid_points_hal_selected,
        "theta_selected": theta_selected,
        "b_jk": b_jk_pruned,
        "delta_j": delta_j,
        "grid_eval": grid_eval
    }

def compute_total_log_likelihood(data, results):
    """
    Compute the total log-likelihood of the observed data given the estimated density.
    """
    estimated_density = results['estimated_density']
    grid_midpoints = results['grid_midpoints']
    delta_j = results['delta_j']

    uncensored = data[data['delta'] == 1]
    censored = data[data['delta'] == 0]

    density_interp = interp1d(grid_midpoints, estimated_density, kind='linear',
                               bounds_error=False, fill_value=(estimated_density[0], estimated_density[-1]))
    ll_uncensored = np.sum(np.log(density_interp(uncensored['T_tilde'].values)))

    cdf = np.cumsum(estimated_density * delta_j)
    survival = 1 - cdf
    survival_interp = interp1d(grid_midpoints, survival, kind='linear',
                               bounds_error=False, fill_value=(1, 0))
    ll_censored = np.sum(np.log(survival_interp(censored['T_tilde'].values)))
    return ll_uncensored + ll_censored

# Helper functions
def split_data_k_folds(data, k):
    """
    Split data into k folds for cross-validation and yield training and test sets.

    Parameters:
    - data: pd.DataFrame, the dataset to split
    - k: int, number of folds

    Yields:
    - data_train: pd.DataFrame, training data for the current fold
    - data_valid: pd.DataFrame, validation data for the current fold
    """
    n = len(data)
    indices = np.arange(n)
    np.random.shuffle(indices)
    fold_size = n // k

    for i in range(k):
        test_indices = indices[i * fold_size: (i + 1) * fold_size]
        train_indices = np.setdiff1d(indices, test_indices)
        data_train = data.iloc[train_indices].reset_index(drop=True)
        data_valid = data.iloc[test_indices].reset_index(drop=True)
        yield data_train, data_valid

def compute_validation_risk_for_lambda(args):
    """
    Compute mean validation log-likelihood (risk) for a given lambda.
    """
    lamb, data, k, threshold,smoothness_order = args
    risks = []
    for train, valid in split_data_k_folds(data, k):
        res = IPCW_HAL_init(train, threshold=threshold, norm_constraint=lamb,smoothness_order=smoothness_order)
        risk = compute_total_log_likelihood(valid, res)
        risks.append(risk)
    return lamb, np.mean(risks)

def CV_IPCW_HAL(data, k, lambda_values, threshold=1e-4, n_jobs=-1,smoothness_order=1):
    """
    Perform k-fold cross-validation over candidate lambda values and return the best lambda.
    """
    args = [(lamb, data, k, threshold,smoothness_order) for lamb in lambda_values]
    if n_jobs == 1:
        results = [compute_validation_risk_for_lambda(arg) for arg in args]
    else:
        with Pool(processes=n_jobs if n_jobs != -1 else None) as pool:
            results = pool.map(compute_validation_risk_for_lambda, args)
    mean_risks = dict(results)
    best_lambda = max(mean_risks, key=mean_risks.get)
    return best_lambda, mean_risks


def precompute_global_cdf(theta_selected, grid_points_hal_selected, n_grid=500,smoothness_order=1):
    """
    Precompute the density and CDF on a global grid from 0 to 1.

    Parameters:
    -----------
    theta_selected : np.ndarray
        The estimated HAL coefficients.
    grid_points_hal_selected : np.ndarray
        The knots / grid points used for the HAL basis.
    n_grid : int
        Number of points in the global evaluation grid from 0 to 1.

    Returns:
    --------
    global_grid : np.ndarray
        Sorted points in [0, 1] (length ~ n_grid + len(grid_points_hal_selected)).
    global_cdf : np.ndarray
        CDF values corresponding to each point in global_grid, scaled to end at 1.
    """
    # Create a base grid [0, 1] plus the HAL knots
    linspace_grid = np.linspace(0, 1, n_grid)
    combined_grid = np.concatenate((linspace_grid, grid_points_hal_selected))
    global_grid = np.unique(combined_grid)
    global_grid = np.sort(global_grid)

    # Midpoints for density approximation
    midpoints = (global_grid[:-1] + global_grid[1:]) / 2
    data_grid = pd.DataFrame({'W1': midpoints})

    # Create basis and evaluate log-density
    basis_tensor = create_basis_functions(data_grid, grid_points_hal_selected,smoothness_order)  # your HAL basis
    b_jk = basis_tensor.numpy()
    estimated_log_density = b_jk @ theta_selected
    estimated_density = np.exp(estimated_log_density)

    # Delta between adjacent grid points
    delta = global_grid[1:] - global_grid[:-1]

    # Normalize so the integral is 1
    integral = np.sum(estimated_density * delta)
    estimated_density /= integral

    # Build the CDF
    cdf_values = np.cumsum(estimated_density * delta)
    # We ensure final cdf is exactly 1.0
    cdf_values[-1] = 1.0

    # We store the CDF at the right endpoints, i.e. global_grid[1:].
    # For convenience, let's make them the same length.
    # Let global_grid_right = global_grid[1:] (endpoints).
    # Then cdf at that point is cdf_values.
    # We'll keep them the same length to use np.interp nicely.
    global_grid_right = global_grid[1:]

    return global_grid_right, cdf_values


def truncated_invert_sampling(coarsening_start, global_grid, global_cdf, num_samples=5):
    """
    Sample from the truncated distribution on [coarsening_start, 1].

    Parameters:
    -----------
    coarsening_start : float
        The lower bound for truncation.
    global_grid : np.ndarray
        The grid over [0, 1], sorted, length N.
    global_cdf : np.ndarray
        The precomputed global CDF values at global_grid, length N.
    num_samples : int
        Number of samples to draw.

    Returns:
    --------
    samples : np.ndarray
        Array of shape (num_samples,) containing the truncated samples.
    """
    # If coarsening_start >= 1, no space to sample
    if coarsening_start >= 1:
        return np.full(num_samples, 1.0)

    # Find the CDF at coarsening_start (via interpolation)
    cdf_start = np.interp(coarsening_start, global_grid, global_cdf)

    # We'll sample from the truncated portion [cdf_start, 1].
    # So we draw uniform random numbers in that range
    random_probs = cdf_start + (1 - cdf_start) * np.random.rand(num_samples)

    # Invert using the global CDF
    samples = np.interp(random_probs, global_cdf, global_grid)
    return samples



def E_step(data, result, num_samples=5, n_grid=500,smoothness_order=1):
    """
    In the E-step, for each censored observation, impute latent event times
    via truncated inverse sampling from the estimated density.
    """
    uncensored = data[data['delta'] == 1].copy()
    censored = data[data['delta'] == 0].copy()

    theta_sel = result['theta_selected']
    knots_sel = result['grid_points_hal_selected']

    # Precompute the global CDF over a fine grid
    global_grid, global_cdf = precompute_global_cdf(theta_sel, knots_sel, n_grid=n_grid,smoothness_order=smoothness_order)

    imputed_list = []
    t0 = time.time()
    for idx, row in censored.iterrows():
        t = row['T_tilde']
        # Sample num_samples points from the truncated density on [t,1]
        samples = truncated_invert_sampling(t, global_grid, global_cdf, num_samples=num_samples)
        samples_df = pd.DataFrame({'T_tilde': samples, 'delta': 1, 'weights': 1/num_samples})
        imputed_list.append(samples_df)
    t1 = time.time()
    print(f"E-step sampling loop time: {t1 - t0:.4f} sec")

    if imputed_list:
        imputed = pd.concat(imputed_list, ignore_index=True)
    else:
        imputed = pd.DataFrame(columns=['T_tilde','delta','weights'])

    uncensored['weights'] = 1
    uncensored['W1'] = uncensored['T_tilde']
    imputed['W1'] = imputed['T_tilde']

    augmented = pd.concat([uncensored[['T_tilde','delta','weights','W1']], imputed], ignore_index=True)
    return augmented

def M_step(augmented, results, old_theta, norm_constraint=20,smoothness_order=1):
    """
    The M-step re–estimates the density parameters using the augmented (imputed) data.
    """
    t0 = time.time()
    knots_sel = results['grid_points_hal_selected']
    # Build design matrix for augmented data
    basis_tensor = create_basis_functions(augmented, knots_sel,smoothness_order)
    b_ik = basis_tensor.detach().numpy()

    # Use a full evaluation grid for normalization
    grid_eval = np.linspace(0, 1, 200)
    combined = np.concatenate((grid_eval, knots_sel))
    grid_eval = np.sort(np.unique(combined))
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})
    basis_grid_tensor = create_basis_functions(data_grid, knots_sel,smoothness_order)
    b_jk = basis_grid_tensor.numpy()

    t1 = time.time()
    print(f"M-step Design Matrix Calculation time (sec): {t1-t0:.4f}")

    t0_opt = time.time()
    K = len(knots_sel) + 1
    theta = cp.Variable(K)
    weights = augmented['weights'].values
    n_weighted = np.sum(weights)
    first_term = -cp.sum((theta[0] + b_ik @ theta[1:]) @ weights)
    delta_j = grid_eval[1:] - grid_eval[:-1]
    log_delta_j = np.log(delta_j)
    log_density_grid = theta[0] + b_jk @ theta[1:]
    log_terms = log_delta_j + log_density_grid
    log_Z = cp.log_sum_exp(log_terms)
    second_term = n_weighted * log_Z
    loss = first_term + second_term
    constraints = [cp.norm1(theta) <= norm_constraint]
    prob = cp.Problem(cp.Minimize(loss), constraints)
    theta.value = old_theta

    try:
        prob.solve(solver="ECOS", warm_start=True)
    except Exception as e:
        print("ECOS solver failed in M_step, falling back to SCS:", e)
        prob.solve(solver="SCS", warm_start=True)

    t1_opt = time.time()
    print(f"M-step CVXPY optimize time (sec): {t1_opt-t0_opt:.4f}")

    theta_val = theta.value
    theta_intercept = theta_val[0]
    theta_sel_new = theta_val[1:]

    grid_eval = np.linspace(0, 1, 1000)
    grid_midpoints = (grid_eval[:-1] + grid_eval[1:]) / 2
    data_grid = pd.DataFrame({'W1': grid_midpoints})
    basis_grid_tensor = create_basis_functions(data_grid, knots_sel,smoothness_order)
    b_jk = basis_grid_tensor.numpy()
    delta_j = grid_eval[1:] - grid_eval[:-1]
    estimated_log_density = theta_intercept + b_jk @ theta_sel_new
    estimated_density = np.exp(estimated_log_density)
    estimated_density /= np.sum(estimated_density * delta_j)

    updated = {
        "theta_value": theta_val,
        "theta_selected": theta_sel_new,
        "theta_intercept": theta_intercept,
        "estimated_density": estimated_density,
        "grid_midpoints": grid_midpoints,
        "grid_points_hal_selected": knots_sel,
        "b_jk": b_jk,
        "delta_j": delta_j,
        "grid_eval": grid_eval
    }
    return updated

def EM_HAL_algorithm(data, initial_results, tolerance=1e-6, max_iterations=100, num_samples=5, norm_constraint=20,smoothness_order=1):
    """
    Performs the EM algorithm for first-order HAL density estimation.
    """
    iteration = 0
    previous_ll = None
    log_likelihoods = []
    current = initial_results

    init_ll = compute_total_log_likelihood(data, current)
    print(f"Initial Log-Likelihood: {init_ll}")
    log_likelihoods.append(init_ll)

    while iteration < max_iterations:
        print(f"Iteration {iteration+1}")
        t0 = time.time()
        augmented = E_step(data, current, num_samples=num_samples,smoothness_order=smoothness_order)
        t1 = time.time()
        print(f"E-step time (sec): {t1-t0:.4f}")

        t2 = time.time()
        old_theta = current.get("theta_value", None)
        updated = M_step(augmented, current, old_theta, norm_constraint=norm_constraint,smoothness_order=smoothness_order)
        t3 = time.time()
        print(f"M-step time (sec): {t3-t2:.4f}")

        total_ll = compute_total_log_likelihood(data, updated)
        print(f"Total Log-Likelihood: {total_ll}")
        log_likelihoods.append(total_ll)

        if previous_ll is not None:
            if abs(total_ll - previous_ll) < tolerance:
                print(f"Convergence achieved at iteration {iteration+1}")
                break
        previous_ll = total_ll
        current = updated
        iteration += 1
    print("EM algorithm completed.")
    return current, log_likelihoods

