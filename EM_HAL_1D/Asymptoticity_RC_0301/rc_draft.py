def compute_survival_from_density(estimator_dict, smoothness_order=1, grid_eval=None):
    """
    Compute the survival function from the estimated density using exact integration
    under the assumption that the log-density is modeled as a first-order (linear) spline.

    Returns the survival function evaluated on the grid.

    Parameters:
    -----------
    estimator_dict : dict
        Dictionary containing the estimated density information. It should include:
          - 'grid_eval' or a default grid will be used,
          - 'grid_points_hal_selected': knots for the HAL basis,
          - 'theta_intercept' and 'theta_selected' (or 'theta_value') for the density model.
    smoothness_order : int, default 1
        The order of smoothness for the HAL basis functions.
    grid_eval : array-like, optional
        Grid points over which to evaluate the survival function.
        If None, defaults to np.linspace(0, 1, 1000).

    Returns:
    --------
    survival : np.ndarray
        The survival function evaluated on grid_eval.
    grid_eval : np.ndarray
        The grid used for evaluation.
    """
    if grid_eval is None:
        grid_eval = estimator_dict.get('grid_eval', np.linspace(0, 1, 1000))
    data_grid = pd.DataFrame({'W1': grid_eval})
    knots = estimator_dict['grid_points_hal_selected']
    basis_tensor = create_basis_functions(data_grid, knots, smoothness_order)
    b_jk = basis_tensor.numpy()

    if 'theta_intercept' in estimator_dict:
        theta_intercept = estimator_dict['theta_intercept']
    else:
        theta_intercept = estimator_dict['theta_value'][0]
    if 'theta_selected' in estimator_dict:
        theta_selected = estimator_dict['theta_selected']
    else:
        theta_selected = estimator_dict['theta_value'][1:]

    log_density = theta_intercept + b_jk @ theta_selected
    cdf = np.zeros_like(grid_eval)
    cumulative = 0.0
    for i in range(len(grid_eval) - 1):
        L, R = grid_eval[i], grid_eval[i + 1]
        logf_L, logf_R = log_density[i], log_density[i + 1]
        B = (logf_R - logf_L) / (R - L)
        if np.abs(B) < 1e-8:
            # When B is nearly zero, use a simple rectangle rule.
            integral = np.exp(logf_L) * (R - L)
        else:
            delta = R - L
            # Use np.expm1 for numerical stability: exp(B*delta) - 1
            integral = np.exp(logf_L) / B * np.expm1(B * delta)
        cumulative += integral
        cdf[i + 1] = cumulative

    total_int = cumulative
    if total_int <= 0:
        raise ValueError("Total integral of the density is non-positive.")
    cdf /= total_int
    survival = 1 - cdf
    return survival, grid_eval


def compute_survival_probabilities(estimator_dict, evaluation_points, smoothness_order=1,grid_eval=None):
    """
    Compute survival probabilities at specified evaluation points based on the estimated density.
    """
    survival, grid_eval = compute_survival_from_density(estimator_dict, grid_eval=grid_eval,smoothness_order=smoothness_order)
    surv_probs = np.interp(evaluation_points, grid_eval, survival, left=1.0, right=0.0)
    return surv_probs

