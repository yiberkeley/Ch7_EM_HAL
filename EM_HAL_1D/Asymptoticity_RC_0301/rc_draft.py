# Multiple Experiment Runner
# ---------------------------
def run_multiple_experiments(n_experiments=10, n_samples=1000,
                             evaluation_points=np.linspace(0.02, 0.98, 20),
                             candidate_lambdas=[55, 60, 65, 70],
                             n_jobs=-1,
                             smoothness_order=1,
                             ridge=0):
    seeds = [12776 + i for i in range(n_experiments)]
    experiment_func = partial(run_single_experiment, n_samples=n_samples,
                              evaluation_points=evaluation_points,
                              candidate_lambdas=candidate_lambdas,
                              smoothness_order=smoothness_order,
                              ridge=ridge)
    with Pool(processes=n_jobs if n_jobs != -1 else None) as pool:
        results = pool.map(experiment_func, seeds)

    # Assemble density and survival estimates into DataFrames (rows: evaluation points, columns: experiments)
    exp_ids = [f"Exp_{i+1}" for i in range(n_experiments)]
    init_density_df = pd.DataFrame(np.column_stack([res["initial_density"] for res in results]),
                                   index=evaluation_points, columns=exp_ids)
    final_density_df = pd.DataFrame(np.column_stack([res["final_density"] for res in results]),
                                    index=evaluation_points, columns=exp_ids)
    init_survival_df = pd.DataFrame(np.column_stack([res["initial_survival"] for res in results]),
                                    index=evaluation_points, columns=exp_ids)
    final_survival_df = pd.DataFrame(np.column_stack([res["final_survival"] for res in results]),
                                     index=evaluation_points, columns=exp_ids)
    init_density_df_se = pd.DataFrame(np.column_stack([res["initial_density_se"] for res in results]),
                                    index=evaluation_points, columns=exp_ids)
    final_density_df_se = pd.DataFrame(np.column_stack([res["final_density_se"] for res in results]),
                                    index=evaluation_points, columns=exp_ids)
    init_survival_df_se = pd.DataFrame(np.column_stack([res["initial_survival_se"] for res in results]),
                                    index=evaluation_points, columns=exp_ids)
    final_survival_df_se = pd.DataFrame(np.column_stack([res["final_survival_se"] for res in results]),
                                    index=evaluation_points, columns=exp_ids)
    best_lambda_df = pd.DataFrame({
        "Experiment": exp_ids,
        "Best_Lambda": [res["best_lambda"] for res in results]
    })
    return init_density_df, final_density_df, init_survival_df, final_survival_df, \
    init_density_df_se,final_density_df_se, init_survival_df_se, final_survival_df_se, best_lambda_df

