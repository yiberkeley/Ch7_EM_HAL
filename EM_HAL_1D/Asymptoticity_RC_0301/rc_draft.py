# Single Experiment Function
# ---------------------------
def run_single_experiment(seed, n_samples=1000,
                          evaluation_points=np.linspace(0, 1, 100),
                          candidate_lambdas=[55, 60, 65, 70],
                          smoothness_order=1,
                          ridge=0):
    """
    Run one complete experiment:
      - Data Generation: Simulate true event times (truncated normal) and censoring times (uniform).
      - Create right–censored observations.
      - Use 5–fold cross-validation over candidate lambdas to select the best lambda.
      - Compute an initial density estimate via IPCW_HAL_init and refine it via EM_HAL_algorithm.
      - Evaluate the estimated density and compute the plug–in survival function.
    Returns a dictionary with:
      - 'initial_density': density estimates (on evaluation_points) from the initial estimator,
      - 'final_density': density estimates (on evaluation_points) from the EM–refined estimator,
      - 'initial_survival': survival probabilities (on evaluation_points) from the initial estimator,
      - 'final_survival': survival probabilities (on evaluation_points) from the refined estimator,
      - 'best_lambda': the best lambda chosen by CV,
      - 'evaluation_points': the evaluation grid.
    """
    np.random.seed(seed)
    T = generate_truncated_normal(n_samples)
    C = generate_uniform(n_samples)
    data = convert_to_survival_data(T, C)

    k = 5
    best_lambda, cv_risks = CV_IPCW_HAL(data, k, candidate_lambdas, threshold=1e-4, n_jobs=1,smoothness_order=smoothness_order)

    init_res = IPCW_HAL_init(data, threshold=1e-4, norm_constraint=best_lambda,smoothness_order=smoothness_order)
    final_res, _ = EM_HAL_algorithm(data, init_res, tolerance=0.05, max_iterations=200,
                                    num_samples=200, norm_constraint=5 * best_lambda,smoothness_order=smoothness_order)

    print('Now to get the estimates and esimated se')
    # Evaluate density by linear interpolation on the final grid
    init_density_eval = np.interp(evaluation_points, init_res["grid_midpoints"], init_res["estimated_density"])
    final_density_eval = np.interp(evaluation_points, final_res["grid_midpoints"], final_res["estimated_density"])

    init_surv_probs = compute_survival_probabilities(init_res, evaluation_points,smoothness_order)
    final_surv_probs = compute_survival_probabilities(final_res, evaluation_points,smoothness_order)



    cov_beta = estimate_covariance_beta(data, init_res, ridge = ridge,smoothness_order=smoothness_order)
    ci_density_df = density_confidence_interval(evaluation_points, init_res, cov_beta, alpha=0.05,smoothness_order=smoothness_order)
    initial_density_se=ci_density_df['se']
    grid, grad_f_grid, delta = precompute_grad_f_grid(init_res, grid_size=1000,smoothness_order=smoothness_order)
    surv_ci_df = survival_confidence_interval_precomputed(evaluation_points, init_res, cov_beta, grid, grad_f_grid, delta, alpha=0.05)
    initial_survival_se=surv_ci_df['se']

    cov_beta = estimate_covariance_beta(data, final_res, ridge = ridge,smoothness_order=smoothness_order)
    ci_density_df = density_confidence_interval(evaluation_points, final_res, cov_beta, alpha=0.05,smoothness_order=smoothness_order)
    final_density_se=ci_density_df['se']
    grid, grad_f_grid, delta = precompute_grad_f_grid(final_res, grid_size=1000,smoothness_order=smoothness_order)
    surv_ci_df = survival_confidence_interval_precomputed(evaluation_points, final_res, cov_beta, grid, grad_f_grid, delta, alpha=0.05)
    final_survival_se=surv_ci_df['se']



    return {
        "initial_density": init_density_eval,
        "final_density": final_density_eval,
        "initial_density_se": initial_density_se,
        "final_density_se": final_density_se,
        "initial_survival": init_surv_probs,
        "final_survival": final_surv_probs,
        "initial_survival_se": initial_survival_se,
        "final_survival_se": final_survival_se,
        "best_lambda": best_lambda,
        "evaluation_points": evaluation_points,
        "cv_risks": cv_risks
    }

