def EM_targeting_algorithm_bivariate(data, initial_model, targeting_pairs, norm_constraint_targeting,
                                     num_samples=5, tolerance=1e-3, max_iterations=50, n_points=50,
                                     integration_grid_T1=None, integration_grid_T2=None):
    """
    Perform an iterative EM procedure for updating the targeting (additional) basis coefficients.
    The fixed (pruned) coefficients remain fixed.

    Parameters:
      - data: DataFrame with columns 'T1_tilde', 'T2_tilde', 'delta1', 'delta2'
      - initial_model: Dictionary (as returned by your initial_fit/EM_HAL_algorithm) containing
                       the fixed (pruned) parameters and grid information.
      - targeting_pairs: List of (t1, t2) pairs defining the targeting basis.
      - norm_constraint_targeting: L1–norm constraint for the targeting coefficients.
      - num_samples, tolerance, max_iterations, n_points, integration_grid_T1, integration_grid_T2:
           Options for the imputation/integration steps.

    Returns:
      - final_targeted_model: Dictionary containing the fixed part (old_theta) and updated targeting coefficients.
      - log_likelihoods: A list with the observed log–likelihood at each iteration.
    """
    # Fixed part from the pruned model:
    old_theta = initial_model["theta_pruned"]
    selected_indices = initial_model["selected_indices"]
    grid_T1 = initial_model["grid_T1"]
    grid_T2 = initial_model["grid_T2"]
    interaction_pairs = initial_model["interaction_pairs"]

    # Initialize targeting coefficients (e.g. zeros)
    r = len(targeting_pairs)
    theta_targeting_current = np.zeros(r)

    log_likelihoods = []

    for it in range(max_iterations):
        print(f"Targeting EM iteration {it+1}")
        # E-step: augment the data using the current full model (fixed + targeting)
        augmented_data = E_step_bivariate_targeting(
            data, old_theta, theta_targeting_current, grid_T1, grid_T2, interaction_pairs,
            selected_indices, targeting_pairs, num_samples, n_points, integration_grid_T1, integration_grid_T2
        )
        # M-step: update the targeting coefficients using your targeting M–step routine.
        # (Here we call your previously defined targeting_M_step_bivariate.)
        updated_results = targeting_M_step_bivariate(
            augmented_data, initial_model, old_theta, targeting_pairs, norm_constraint=norm_constraint_targeting,
            n_points=n_points, integration_grid_T1=integration_grid_T1, integration_grid_T2=integration_grid_T2
        )
        theta_targeting_new = updated_results["theta_targeting"]

        # Compute the observed log–likelihood for the full (targeted) model:
        obs_ll = compute_observed_log_likelihood_bivariate_targeting(
            data, old_theta, theta_targeting_new, grid_T1, grid_T2, interaction_pairs,
            selected_indices, targeting_pairs, n_points, integration_grid_T1, integration_grid_T2
        )
        log_likelihoods.append(obs_ll)
        print(f"  Observed log–likelihood: {obs_ll:.4f}")

        # Check for convergence:
        if it > 0 and abs(log_likelihoods[-1] - log_likelihoods[-2]) < tolerance:
            print("Convergence achieved in targeting EM.")
            break

        theta_targeting_current = theta_targeting_new

    final_targeted_model = {
        "old_theta": old_theta,                   # fixed part (unchanged)
        "theta_targeting": theta_targeting_current, # updated targeting coefficients
        "theta_pruned": old_theta,                # for compatibility with your naming
        "selected_indices": selected_indices,
        "grid_T1": grid_T1,
        "grid_T2": grid_T2,
        "interaction_pairs": interaction_pairs,
        "targeting_pairs": targeting_pairs
    }

    return final_targeted_model, log_likelihoods


