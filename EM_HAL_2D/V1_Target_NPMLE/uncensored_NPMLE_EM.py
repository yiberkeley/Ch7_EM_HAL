# 4. Initial Fit with L1–Constraint and Pruning (CV Stage)
# =============================================================================
def initial_fit_bivariate(data, norm_constraint, grid_T1, grid_T2, interaction_pairs,
                          threshold=1e-4, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    (a) Impute missing values uniformly.
    (b) Fit the full model using all basis functions.
    (c) Prune coefficients whose absolute value is below threshold.
    """
    data_imputed = impute_uniform_bivariate(data)
    X = create_bivariate_basis_functions(data_imputed, grid_T1, grid_T2, interaction_pairs)
    n, p = X.shape
    # Use the supplied integration grid (or uniform grid if None)
    grid_eval, int_t1, int_t2, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    X_grid = create_bivariate_basis_functions(grid_eval, grid_T1, grid_T2, interaction_pairs)
    area_elements = weights.ravel()  # flatten the weight matrix
    theta = cp.Variable(p)
    data_term = -cp.sum(X @ theta)
    # Use constant weights in the cvxpy log-sum-exp term:
    log_terms = X_grid @ theta + cp.Constant(np.log(area_elements))
    log_Z = cp.log_sum_exp(log_terms)
    norm_term = n * log_Z
    objective = cp.Minimize(data_term + norm_term)
    constraints = [cp.norm1(theta[1:]) <= norm_constraint]
    prob = cp.Problem(objective, constraints)
    prob.solve(solver="SCS")
    theta_fitted = theta.value
    selected_indices = [0] + [i for i in range(1, p) if abs(theta_fitted[i]) >= threshold]
    theta_pruned = theta_fitted[selected_indices]
    return {
        "theta_full": theta_fitted,
        "theta_pruned": theta_pruned,
        "selected_indices": np.array(selected_indices),
        "grid_T1": grid_T1,
        "grid_T2": grid_T2,
        "interaction_pairs": interaction_pairs
    }

