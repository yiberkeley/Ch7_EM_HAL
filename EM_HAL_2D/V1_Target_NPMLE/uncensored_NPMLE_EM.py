def compute_density(model, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    Compute the estimated density on a grid using the full (fixed + targeting, if present)
    model. Returns the integration grid (as a DataFrame), grid values for T1 and T2,
    and a 2D array of estimated densities.
    """
    grid_eval, t1_vals, t2_vals, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    area_elements = weights.ravel()
    log_f = compute_full_log_density(model, grid_eval)
    f = safe_exp(log_f)
    Z = np.sum(f * area_elements)
    density = f / Z
    density = density.reshape(weights.shape)
    return grid_eval, t1_vals, t2_vals, density


def compute_survival(model, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    Compute the survival function S(t1,t2)=P(T1 > t1, T2 > t2) from the estimated density.
    Uses the inclusion-exclusion formula:
         S(t1,t2) = 1 - F_T1(t1) - F_T2(t2) + F(t1,t2)
    """
    # Get density and grid information.
    _, t1_vals, t2_vals, density = compute_density(model, n_points=n_points,
                                                   integration_grid_T1=integration_grid_T1,
                                                   integration_grid_T2=integration_grid_T2)
    _, _, _, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)

    # Compute joint CDF by cumulative summation.
    cdf = np.cumsum(np.cumsum(density * weights, axis=0), axis=1)
    F1 = cdf[-1, :]  # marginal CDF for T1 (last row)
    F2 = cdf[:, -1]  # marginal CDF for T2 (last column)
    survival = 1 - F1[np.newaxis, :] - F2[:, np.newaxis] + cdf
    return t1_vals, t2_vals, survival


