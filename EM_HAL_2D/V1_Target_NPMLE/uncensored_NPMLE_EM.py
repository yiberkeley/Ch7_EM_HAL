# 6. Cross–Validation Procedure for the Initial Fit
# =============================================================================
def split_data_k_folds(data, k):
    n = len(data)
    indices = np.arange(n)
    np.random.shuffle(indices)
    fold_size = n // k
    folds = []
    for i in range(k):
        test_idx = indices[i*fold_size:(i+1)*fold_size]
        train_idx = np.setdiff1d(indices, test_idx)
        train_data = data.iloc[train_idx].reset_index(drop=True)
        test_data = data.iloc[test_idx].reset_index(drop=True)
        folds.append((train_data, test_data))
    return folds

def compute_cv_risk_for_lambda_bivariate(args):
    """
    For one candidate lambda (L1 norm constraint), perform k–fold CV.
    """
    lamb, data, k, grid_T1, grid_T2, interaction_pairs, threshold, n_points, integration_grid_T1, integration_grid_T2 = args
    folds = split_data_k_folds(data, k)
    risks = []
    for train_data, valid_data in folds:
        model = initial_fit_bivariate(train_data, norm_constraint=lamb,
                                      grid_T1=grid_T1, grid_T2=grid_T2,
                                      interaction_pairs=interaction_pairs,
                                      threshold=threshold, n_points=n_points,
                                      integration_grid_T1=integration_grid_T1,
                                      integration_grid_T2=integration_grid_T2)
        risk = compute_validation_risk_bivariate(valid_data, model, n_points=n_points,
                                                 integration_grid_T1=integration_grid_T1,
                                                 integration_grid_T2=integration_grid_T2)
        risks.append(risk)
    mean_risk = np.mean(risks)
    return lamb, mean_risk


