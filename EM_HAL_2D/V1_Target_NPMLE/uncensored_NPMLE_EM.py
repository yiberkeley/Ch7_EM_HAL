# Helper function: Sample from a truncated bivariate normal
# =============================================================================
def sample_truncated_bivariate_normal(n_samples, mean, cov, lower, upper):
    """
    Sample from a bivariate normal distribution and reject samples that fall
    outside the rectangular region defined by lower and upper bounds.

    Parameters
    ----------
    n_samples : int
        Number of desired samples.
    mean : list or array-like of length 2
        Mean vector (e.g. [0.5, 0.5]).
    cov : 2x2 array-like
        Covariance matrix.
    lower : list or array-like of length 2
        Lower bounds for T1 and T2 (e.g. [0, 0]).
    upper : list or array-like of length 2
        Upper bounds for T1 and T2 (e.g. [1, 1]).

    Returns
    -------
    samples : np.ndarray, shape (n_samples, 2)
        The accepted samples.
    """
    samples = []
    while len(samples) < n_samples:
        candidate = multivariate_normal.rvs(mean=mean, cov=cov)
        if np.all(candidate >= lower) and np.all(candidate <= upper):
            samples.append(candidate)
    return np.array(samples)

