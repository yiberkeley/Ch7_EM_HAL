def compute_integration_weights(grid_1d):
    """
    Given a sorted 1D array grid_1d, compute integration weights
    using a trapezoidal–like rule.
    """
    grid_1d = np.asarray(grid_1d)
    n = len(grid_1d)
    if n == 1:
        return np.array([1.0])
    dx = np.diff(grid_1d)
    w = np.empty(n)
    w[0] = dx[0] / 2
    w[-1] = dx[-1] / 2
    if n > 2:
        w[1:-1] = (dx[:-1] + dx[1:]) / 2
    return w

def get_integration_grid(integration_grid_T1=None, integration_grid_T2=None, n_points=50):
    """
    If integration_grid_T1 and integration_grid_T2 (1D arrays) are provided,
    create the Cartesian product (as a DataFrame) and compute the outer–product
    of integration weights.
    Otherwise, use a uniform grid over [0,1] with n_points.
    Returns: (grid_df, t1_vals, t2_vals, weights)
      - grid_df is a DataFrame with columns 'T1' and 'T2'
      - t1_vals, t2_vals are the 1D grid arrays
      - weights is a 2D array of the same shape as the grid (for integration).
    """
    if integration_grid_T1 is None or integration_grid_T2 is None:
        # Use uniform grid
        t1_vals = np.linspace(0, 1, n_points)
        t2_vals = np.linspace(0, 1, n_points)
        T1, T2 = np.meshgrid(t1_vals, t2_vals)
        grid_df = pd.DataFrame({'T1': T1.ravel(), 'T2': T2.ravel()})
        dT = 1/(n_points - 1)
        weights = np.full((n_points, n_points), dT * dT)
        return grid_df, t1_vals, t2_vals, weights
    else:
        integration_grid_T1 = np.asarray(integration_grid_T1)
        integration_grid_T2 = np.asarray(integration_grid_T2)
        T1, T2 = np.meshgrid(integration_grid_T1, integration_grid_T2)
        grid_df = pd.DataFrame({'T1': T1.ravel(), 'T2': T2.ravel()})
        w1 = compute_integration_weights(integration_grid_T1)
        w2 = compute_integration_weights(integration_grid_T2)
        weights = np.outer(w2, w1)
        return grid_df, integration_grid_T1, integration_grid_T2, weights

