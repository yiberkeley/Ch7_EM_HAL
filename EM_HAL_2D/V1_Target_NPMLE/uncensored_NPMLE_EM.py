def create_bivariate_basis_functions(data, grid_T1, grid_T2, interaction_pairs=None, selected_indices=None):
    """
    Build the design matrix for a first–order HAL bivariate model.
    (Same as your original code.)
    """
    n = data.shape[0]
    intercept = np.ones((n, 1))
    T1_basis = np.column_stack([ ((data['T1'] >= t).astype(int)) * (data['T1'] - t) for t in grid_T1 ])
    T2_basis = np.column_stack([ ((data['T2'] >= t).astype(int)) * (data['T2'] - t) for t in grid_T2 ])
    if interaction_pairs is not None:
        interaction_basis = np.column_stack([
            (((data['T1'] >= t1).astype(int)) * (data['T1'] - t1)) *
            (((data['T2'] >= t2).astype(int)) * (data['T2'] - t2))
            for t1, t2 in interaction_pairs
        ])
    else:
        interaction_list = []
        for t1 in grid_T1:
            for t2 in grid_T2:
                interaction_list.append(
                    (((data['T1'] >= t1).astype(int)) * (data['T1'] - t1)) *
                    (((data['T2'] >= t2).astype(int)) * (data['T2'] - t2))
                )
        interaction_basis = np.column_stack(interaction_list) if interaction_list else np.empty((n, 0))
    X_full = np.hstack([intercept, T1_basis, T2_basis, interaction_basis])
    if selected_indices is not None:
        return X_full[:, selected_indices]
    else:
        return X_full

def evaluate_joint_density(data, theta, grid_T1, grid_T2, interaction_pairs=None, selected_indices=None):
    """
    Evaluate the (unnormalized) joint density f(T1,T2)=exp(Xθ) at the rows of data.
    """
    X = create_bivariate_basis_functions(data, grid_T1, grid_T2, interaction_pairs, selected_indices)
    return np.exp(X @ theta)

