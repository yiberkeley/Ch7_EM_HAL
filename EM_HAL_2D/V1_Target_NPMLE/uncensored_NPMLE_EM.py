def impute_uniform_bivariate(data):
    data = data.copy()
    imputed_T1 = data['T1_tilde'].copy()
    imputed_T2 = data['T2_tilde'].copy()
    mask1 = data['delta1'] == 0
    imputed_T1[mask1] = data.loc[mask1, 'T1_tilde'] + (1 - data.loc[mask1, 'T1_tilde']) * np.random.rand(mask1.sum())
    mask2 = data['delta2'] == 0
    imputed_T2[mask2] = data.loc[mask2, 'T2_tilde'] + (1 - data.loc[mask2, 'T2_tilde']) * np.random.rand(mask2.sum())
    data_imputed = data.copy()
    data_imputed['T1'] = imputed_T1
    data_imputed['T2'] = imputed_T2
    return data_imputed

