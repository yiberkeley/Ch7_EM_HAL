def compute_full_log_density(model, grid_eval):
    """
    Compute the full linear predictor on grid_eval. This is the sum of the fixed (pruned)
    part plus, if present, the targeting part.
    """
    # Fixed (pruned) part:
    X_fixed = create_bivariate_basis_functions(
        grid_eval,
        model["grid_T1"],
        model["grid_T2"],
        model["interaction_pairs"],
        model["selected_indices"]
    )
    log_fixed = X_fixed @ model["theta_pruned"]

    # Check if a targeting component exists:
    if "theta_targeting" in model and "targeting_pairs" in model:
        X_target = create_targeting_basis_functions_bivariate(grid_eval, model["targeting_pairs"])
        if hasattr(X_target, "numpy"):
            X_target = X_target.numpy()
        log_target = X_target @ model["theta_targeting"]
        return log_fixed + log_target
    else:
        return log_fixed


