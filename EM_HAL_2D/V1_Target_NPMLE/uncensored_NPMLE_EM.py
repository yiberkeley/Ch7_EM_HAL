def compute_Z_pruned(theta_pruned, grid_T1, grid_T2, interaction_pairs, selected_indices,
                     n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    grid_eval, int_t1, int_t2, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    X_grid = create_bivariate_basis_functions(grid_eval, grid_T1, grid_T2, interaction_pairs, selected_indices)
    area_elements = weights.ravel()
    log_f_grid = X_grid @ theta_pruned
    log_Z = logsumexp(log_f_grid + np.log(area_elements))
    Z = np.exp(log_Z)
    return Z, log_Z

def validation_log_prob_bivariate(row, theta_pruned, grid_T1, grid_T2, interaction_pairs, selected_indices,
                                  n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    Compute the log–probability that (T1,T2) falls in the coarsening set for one observation.
    The integration uses the supplied (or uniform) integration grid.
    """
    Z, log_Z = compute_Z_pruned(theta_pruned, grid_T1, grid_T2, interaction_pairs, selected_indices,
                                n_points=n_points, integration_grid_T1=integration_grid_T1, integration_grid_T2=integration_grid_T2)
    t1_obs = row['T1_tilde']
    t2_obs = row['T2_tilde']
    if row['delta1'] == 1 and row['delta2'] == 1:
        df_pt = pd.DataFrame({'T1': [t1_obs], 'T2': [t2_obs]})
        X_pt = create_bivariate_basis_functions(df_pt, grid_T1, grid_T2, interaction_pairs, selected_indices)
        log_f_pt = X_pt @ theta_pruned
        return log_f_pt[0] - log_Z
    elif row['delta1'] == 1 and row['delta2'] == 0:
        # integrate over T2 in [t2_obs,1]
        if integration_grid_T2 is None:
            t2_grid = np.linspace(t2_obs, 1, n_points)
            dt = (1 - t2_obs) / (n_points - 1)
            weights_1d = np.full_like(t2_grid, dt)
        else:
            t2_grid = np.array(integration_grid_T2)
            t2_grid = t2_grid[t2_grid >= t2_obs]
            if len(t2_grid) < 2:
                t2_grid = np.linspace(t2_obs, 1, n_points)
            weights_1d = compute_integration_weights(t2_grid)
        T1_arr = np.full_like(t2_grid, t1_obs)
        df_temp = pd.DataFrame({'T1': T1_arr, 'T2': t2_grid})
        X_temp = create_bivariate_basis_functions(df_temp, grid_T1, grid_T2, interaction_pairs, selected_indices)
        log_vals = X_temp @ theta_pruned
        log_integral = logsumexp(log_vals + np.log(weights_1d))
        return log_integral - log_Z
    elif row['delta1'] == 0 and row['delta2'] == 1:
        # integrate over T1 in [t1_obs,1]
        if integration_grid_T1 is None:
            t1_grid = np.linspace(t1_obs, 1, n_points)
            dt = (1 - t1_obs) / (n_points - 1)
            weights_1d = np.full_like(t1_grid, dt)
        else:
            t1_grid = np.array(integration_grid_T1)
            t1_grid = t1_grid[t1_grid >= t1_obs]
            if len(t1_grid) < 2:
                t1_grid = np.linspace(t1_obs, 1, n_points)
            weights_1d = compute_integration_weights(t1_grid)
        T2_arr = np.full_like(t1_grid, row['T2_tilde'])
        df_temp = pd.DataFrame({'T1': t1_grid, 'T2': T2_arr})
        X_temp = create_bivariate_basis_functions(df_temp, grid_T1, grid_T2, interaction_pairs, selected_indices)
        log_vals = X_temp @ theta_pruned
        log_integral = logsumexp(log_vals + np.log(weights_1d))
        return log_integral - log_Z
    else:
        # integrate over both T1 in [t1_obs,1] and T2 in [t2_obs,1]
        if integration_grid_T1 is None or integration_grid_T2 is None:
            t1_grid = np.linspace(t1_obs, 1, n_points)
            t2_grid = np.linspace(t2_obs, 1, n_points)
            dt1 = (1 - t1_obs) / (n_points - 1)
            dt2 = (1 - t2_obs) / (n_points - 1)
            weights_2d = np.full((n_points, n_points), dt1*dt2)
        else:
            t1_grid = np.array(integration_grid_T1)
            t2_grid = np.array(integration_grid_T2)
            t1_grid = t1_grid[t1_grid >= t1_obs]
            t2_grid = t2_grid[t2_grid >= t2_obs]
            if len(t1_grid) < 2 or len(t2_grid) < 2:
                t1_grid = np.linspace(t1_obs, 1, n_points)
                t2_grid = np.linspace(t2_obs, 1, n_points)
                dt1 = (1 - t1_obs) / (n_points - 1)
                dt2 = (1 - t2_obs) / (n_points - 1)
                weights_2d = np.full((n_points, n_points), dt1*dt2)
            else:
                w1 = compute_integration_weights(t1_grid)
                w2 = compute_integration_weights(t2_grid)
                weights_2d = np.outer(w2, w1)
        T1_mesh, T2_mesh = np.meshgrid(t1_grid, t2_grid)
        df_temp = pd.DataFrame({'T1': T1_mesh.ravel(), 'T2': T2_mesh.ravel()})
        X_temp = create_bivariate_basis_functions(df_temp, grid_T1, grid_T2, interaction_pairs, selected_indices)
        log_vals = X_temp @ theta_pruned
        log_integral = logsumexp(log_vals + np.log(weights_2d.ravel()))
        return log_integral - log_Z

def compute_validation_risk_bivariate(data, model, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    total_log_prob = 0.0
    for _, row in data.iterrows():
        total_log_prob += validation_log_prob_bivariate(row, model["theta_pruned"],
                                                        model["grid_T1"],
                                                        model["grid_T2"],
                                                        model["interaction_pairs"],
                                                        model["selected_indices"],
                                                        n_points=n_points,
                                                        integration_grid_T1=integration_grid_T1,
                                                        integration_grid_T2=integration_grid_T2)
    return total_log_prob

