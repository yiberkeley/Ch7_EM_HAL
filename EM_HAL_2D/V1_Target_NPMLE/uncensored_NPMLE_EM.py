def get_density_surfaces_dataframe_multiple(models, truth_params=None, n_points=50,
                                            integration_grid_T1=None, integration_grid_T2=None):
    """
    Compute bivariate density surfaces for multiple models and return a DataFrame.
    
    Parameters:
      models: dict
          Dictionary of models with keys as model names.
      truth_params: dict (optional)
          Dictionary with keys 'mean' and 'cov' for computing the true density.
      n_points: int
          Number of points in each dimension.
      integration_grid_T1, integration_grid_T2: array-like (optional)
          Custom grids for T1 and T2.
          
    Returns:
      df: pandas.DataFrame
          DataFrame with columns 'T1', 'T2' and one column for each model’s density
          (and 'true_density' if truth_params is provided).
    """
    # Obtain integration grid values and weights.
    grid_eval, t1_vals, t2_vals, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    T1, T2 = np.meshgrid(t1_vals, t2_vals)
    
    # Create a dictionary to collect the data.
    data = {'T1': T1.ravel(), 'T2': T2.ravel()}
    
    # If truth parameters are provided, compute the true density.
    if truth_params is not None:
        mean = truth_params.get('mean', [0.5, 0.5])
        cov = truth_params.get('cov', [[0.05, 0.0], [0.0, 0.05]])
        
        # Compute the true density on [0, 1]x[0, 1].
        def compute_true_density_bivariate(t1_vals, t2_vals, mean, cov):
            rv = multivariate_normal(mean=mean, cov=cov)
            # Compute the normalizing constant over the unit square.
            Z = rv.cdf([1, 1]) - rv.cdf([1, 0]) - rv.cdf([0, 1]) + rv.cdf([0, 0])
            T1_grid, T2_grid = np.meshgrid(t1_vals, t2_vals)
            pdf_vals = rv.pdf(np.dstack((T1_grid, T2_grid)))
            return pdf_vals / Z
        
        true_density = compute_true_density_bivariate(t1_vals, t2_vals, mean, cov)
        data['true_density'] = true_density.ravel()
    
    # For each model, compute the normalized density surface.
    for name, model in models.items():
        # Compute the full log density evaluated on the grid.
        log_f = compute_full_log_density(model, grid_eval)
        # Convert log density to density.
        f = safe_exp(log_f)
        # Normalize using the integration weights.
        Z = np.sum(f * weights.ravel())
        density = (f / Z).reshape(weights.shape)
        data[name] = density.ravel()
        
    # Return the results as a DataFrame.
    df = pd.DataFrame(data)
    return df

