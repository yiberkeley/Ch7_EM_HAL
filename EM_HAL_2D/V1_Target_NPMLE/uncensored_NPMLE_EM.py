def create_full_basis_functions(data, model):
    """
    Build the full design matrix for a model.
    If targeting components exist (i.e. if model contains 'theta_targeting' and 'targeting_pairs'),
    the full design is the horizontal concatenation of the fixed design (via create_bivariate_basis_functions)
    and the targeting design (via create_targeting_basis_functions_bivariate).
    Otherwise, it returns the fixed design.
    """
    X_fixed = create_bivariate_basis_functions(data, model["grid_T1"], model["grid_T2"],
                                               model["interaction_pairs"], model["selected_indices"])
    if "theta_targeting" in model and "targeting_pairs" in model:
        X_target = create_targeting_basis_functions_bivariate(data, model["targeting_pairs"])
        if hasattr(X_target, "numpy"):
            X_target = X_target.numpy()
        return np.hstack([X_fixed, X_target])
    else:
        return X_fixed


def integrate_full_design(row, model, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    For a single observation (row), compute the conditional expectation S_i of the full design
    vector (i.e. the integrated full design vector) over the observation’s coarsening set.
    
    The full design vector is obtained by create_full_basis_functions, which concatenates the fixed
    and, if present, targeting components.
    
    Parameters
    ----------
    row : pandas Series
        Must contain at least 'T1_tilde', 'T2_tilde', 'delta1', 'delta2'.
    model : dict
        Contains fixed keys ("theta_pruned", "grid_T1", "grid_T2", "interaction_pairs", "selected_indices")
        and, optionally, targeting keys ("theta_targeting", "targeting_pairs").
    n_points : int, optional
        Number of integration grid points.
    integration_grid_T1, integration_grid_T2 : array-like, optional
        Custom integration grids; if None a uniform grid on [0,1] is used.
    
    Returns
    -------
    S_i : numpy array
        The conditional expectation (a vector with the same dimension as the full design) for the observation.
    """
    # Construct the full parameter vector.
    if "theta_targeting" in model and "targeting_pairs" in model:
        theta_full = np.concatenate([model["theta_pruned"], model["theta_targeting"]])
    else:
        theta_full = model["theta_pruned"]
    
    # CASE 1: Fully observed: integrate over a singleton.
    if row['delta1'] == 1 and row['delta2'] == 1:
        df_pt = pd.DataFrame({'T1': [row['T1_tilde']], 'T2': [row['T2_tilde']]})
        X_full = create_full_basis_functions(df_pt, model)
        return X_full[0]
    
    # CASE 2: T1 observed, T2 censored.
    elif row['delta1'] == 1 and row['delta2'] == 0:
        t1_val = row['T1_tilde']
        t2_min = row['T2_tilde']
        if integration_grid_T2 is None:
            t2_grid = np.linspace(t2_min, 1, n_points)
            dt = (1 - t2_min) / (n_points - 1)
            weights = np.full_like(t2_grid, dt)
        else:
            t2_grid = np.array(integration_grid_T2)
            t2_grid = t2_grid[t2_grid >= t2_min]
            if len(t2_grid) < 2:
                t2_grid = np.linspace(t2_min, 1, n_points)
                dt = (1 - t2_min) / (n_points - 1)
                weights = np.full_like(t2_grid, dt)
            else:
                weights = compute_integration_weights(t2_grid)
        df_temp = pd.DataFrame({'T1': np.full(len(t2_grid), t1_val), 'T2': t2_grid})
        X_full = create_full_basis_functions(df_temp, model)
        f_vals = np.exp(X_full @ theta_full)
        weight_sum = np.sum(f_vals * weights)
        if weight_sum == 0:
            return np.zeros(X_full.shape[1])
        S_i = np.sum((f_vals * weights)[:, None] * X_full, axis=0) / weight_sum
        return S_i
    
    # CASE 3: T1 censored, T2 observed.
    elif row['delta1'] == 0 and row['delta2'] == 1:
        t2_val = row['T2_tilde']
        t1_min = row['T1_tilde']
        if integration_grid_T1 is None:
            t1_grid = np.linspace(t1_min, 1, n_points)
            dt = (1 - t1_min) / (n_points - 1)
            weights = np.full_like(t1_grid, dt)
        else:
            t1_grid = np.array(integration_grid_T1)
            t1_grid = t1_grid[t1_grid >= t1_min]
            if len(t1_grid) < 2:
                t1_grid = np.linspace(t1_min, 1, n_points)
                dt = (1 - t1_min) / (n_points - 1)
                weights = np.full_like(t1_grid, dt)
            else:
                weights = compute_integration_weights(t1_grid)
        df_temp = pd.DataFrame({'T1': t1_grid, 'T2': np.full(len(t1_grid), t2_val)})
        X_full = create_full_basis_functions(df_temp, model)
        f_vals = np.exp(X_full @ theta_full)
        weight_sum = np.sum(f_vals * weights)
        if weight_sum == 0:
            return np.zeros(X_full.shape[1])
        S_i = np.sum((f_vals * weights)[:, None] * X_full, axis=0) / weight_sum
        return S_i
    
    # CASE 4: Both T1 and T2 censored.
    else:
        t1_min = row['T1_tilde']
        t2_min = row['T2_tilde']
        if integration_grid_T1 is None or integration_grid_T2 is None:
            t1_grid = np.linspace(t1_min, 1, n_points)
            t2_grid = np.linspace(t2_min, 1, n_points)
            dt1 = (1 - t1_min) / (n_points - 1)
            dt2 = (1 - t2_min) / (n_points - 1)
            weights_2d = np.full((n_points, n_points), dt1 * dt2)
        else:
            t1_grid = np.array(integration_grid_T1)
            t2_grid = np.array(integration_grid_T2)
            t1_grid = t1_grid[t1_grid >= t1_min]
            t2_grid = t2_grid[t2_grid >= t2_min]
            if len(t1_grid) < 2 or len(t2_grid) < 2:
                t1_grid = np.linspace(t1_min, 1, n_points)
                t2_grid = np.linspace(t2_min, 1, n_points)
                dt1 = (1 - t1_min) / (n_points - 1)
                dt2 = (1 - t2_min) / (n_points - 1)
                weights_2d = np.full((n_points, n_points), dt1 * dt2)
            else:
                w1 = compute_integration_weights(t1_grid)
                w2 = compute_integration_weights(t2_grid)
                weights_2d = np.outer(w2, w1)
        T1_mesh, T2_mesh = np.meshgrid(t1_grid, t2_grid)
        df_temp = pd.DataFrame({'T1': T1_mesh.ravel(), 'T2': T2_mesh.ravel()})
        X_full = create_full_basis_functions(df_temp, model)
        f_vals = np.exp(X_full @ theta_full)
        weights_2d_flat = weights_2d.ravel()
        weight_sum = np.sum(f_vals * weights_2d_flat)
        if weight_sum == 0:
            return np.zeros(X_full.shape[1])
        S_i = np.sum((f_vals * weights_2d_flat)[:, None] * X_full, axis=0) / weight_sum
        return S_i


def compute_scores_unified(data, model, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    Compute full score vectors for the model.
    For each observation i, the score is defined as:
         score_i = S_i - E_full,
    where S_i is the conditional expectation (over the integration region defined by censoring)
    of the full design vector and E_full is the overall expectation computed over [0,1]^2.
    
    This function works for both the initial (fixed-only) and the targeted (fixed+targeting) models.
    """
    # Build a full integration grid.
    grid_eval, _, _, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    weights_flat = weights.ravel()
    # Build the full design on the grid.
    X_full_grid = create_full_basis_functions(grid_eval, model)
    if "theta_targeting" in model and "targeting_pairs" in model:
        theta_full = np.concatenate([model["theta_pruned"], model["theta_targeting"]])
    else:
        theta_full = model["theta_pruned"]
    f_full = np.exp(X_full_grid @ theta_full)
    Z = np.sum(f_full * weights_flat)
    E_full = np.sum((f_full * weights_flat)[:, None] * X_full_grid, axis=0) / Z
    scores = []
    for _, row in data.iterrows():
        S_i = integrate_full_design(row, model, n_points, integration_grid_T1, integration_grid_T2)
        scores.append(S_i - E_full)
    return np.vstack(scores)


def get_survival_surfaces_with_CI_dataframe_multiple(models, data, truth_params=None, n_points=50,
                                                      integration_grid_T1=None, integration_grid_T2=None,
                                                      ridge=1e-4):
    """
    Compute bivariate survival surfaces and corresponding 95% confidence intervals
    for multiple models on a grid.
    
    For each model, this function uses compute_scores_unified to form an empirical
    information matrix for the full parameter vector. Then for each grid point (t1,t2),
    it computes the survival probability via survival_and_gradient_unified and applies the delta method
    to obtain standard errors and 95% Wald-type confidence intervals.
    
    Parameters
    ----------
    models : dict
        Dictionary of models with keys as model names. Each model must contain at least the keys
        used in the unified functions (for the fixed part, and optionally, targeting keys).
    data : pd.DataFrame
        The data used for model fitting (must include columns 'T1_tilde', 'T2_tilde', 'delta1', 'delta2').
    truth_params : dict, optional
        Dictionary with keys 'mean' and 'cov' for computing the true survival.
    n_points : int
        Number of grid points in each dimension.
    integration_grid_T1, integration_grid_T2 : array-like, optional
        Custom grids for T1 and T2; if None, uniform grids over [0,1] are used.
    ridge : float, default 1e-4
        Ridge penalty added to the empirical information matrix.
    
    Returns
    -------
    df : pandas DataFrame
        DataFrame with columns 'T1', 'T2' and for each model three columns:
        "<model>_S", "<model>_CI_lower", and "<model>_CI_upper". Also includes 'true_survival'
        if truth_params is provided.
    """
    survival_dict = {}
    ci_lower_dict = {}
    ci_upper_dict = {}
    model_names = list(models.keys())
    
    # Define grid.
    if integration_grid_T1 is None or integration_grid_T2 is None:
        t1_vals = np.linspace(0, 1, n_points)
        t2_vals = np.linspace(0, 1, n_points)
    else:
        t1_vals = np.array(integration_grid_T1)
        t2_vals = np.array(integration_grid_T2)
    T1, T2 = np.meshgrid(t1_vals, t2_vals)
    
    # Optionally compute the true survival.
    df_dict = {'T1': T1.ravel(), 'T2': T2.ravel()}
    if truth_params is not None:
        true_surv = compute_true_survival_bivariate(t1_vals, t2_vals, 
                                                    mean=truth_params.get('mean', [0.5, 0.5]),
                                                    cov=truth_params.get('cov', [[0.05, 0.0], [0.0, 0.05]]))
        df_dict['true_survival'] = true_surv.ravel()
    
    # For each model, compute the empirical covariance matrix via the unified score function.
    for name in model_names:
        mod = models[name]

        #Compute the survival
        t1_vals, t2_vals, survival = compute_survival(
            models[name], n_points=n_points,
            integration_grid_T1=integration_grid_T1,
            integration_grid_T2=integration_grid_T2)
        # Compute the score matrix on the observed data.
        score_matrix = compute_scores_unified(data, mod, n_points=n_points,
                                              integration_grid_T1=integration_grid_T1,
                                              integration_grid_T2=integration_grid_T2)
        n_obs = data.shape[0]
        I_hat = (score_matrix.T @ score_matrix) / n_obs
        cov_theta = np.linalg.inv(I_hat + ridge * np.eye(I_hat.shape[0]))
        
        # Now, for each grid point, compute survival and its gradient.
        S_vals = []
        CI_lower_vals = []
        CI_upper_vals = []
        # Here we use survival_and_gradient_unified (defined below) to compute survival and gradient.
        survival_flat = survival.ravel() 
        idx=0
        for t1 in t1_vals:
            for t2 in t2_vals:
                S_hat, grad_full = survival_and_gradient_unified(mod, t1, t2, n_points=n_points,
                                                                 integration_grid_T1=integration_grid_T1,
                                                                 integration_grid_T2=integration_grid_T2)
                S_hat=survival_flat[idx]
                se = np.sqrt(grad_full.T @ cov_theta @ grad_full)
                S_vals.append(S_hat)
                CI_lower_vals.append(S_hat - 1.96 * se)
                CI_upper_vals.append(S_hat + 1.96 * se)
                idx=idx+1
        survival_dict[name] = np.array(S_vals).reshape(len(t2_vals), len(t1_vals))
        ci_lower_dict[name] = np.array(CI_lower_vals).reshape(len(t2_vals), len(t1_vals))
        ci_upper_dict[name] = np.array(CI_upper_vals).reshape(len(t2_vals), len(t1_vals))
    
    # Build final DataFrame.
    df = pd.DataFrame({'T1': T1.ravel(), 'T2': T2.ravel()})
    for name in model_names:
        df[name + '_S'] = survival_dict[name].ravel()
        df[name + '_CI_lower'] = ci_lower_dict[name].ravel()
        df[name + '_CI_upper'] = ci_upper_dict[name].ravel()
    if 'true_survival' in df_dict:
        df['true_survival'] = df_dict['true_survival']
    return df


def survival_and_gradient_unified(model, t1_threshold, t2_threshold, n_points=50, 
                                  integration_grid_T1=None, integration_grid_T2=None):
    """
    Compute the survival probability S(t1,t2) and the gradient with respect to the full parameter
    vector. This function works for both the initial model (only fixed components) and the targeted
    model (fixed + targeting components). If targeting components are present in model (i.e. if
    'theta_targeting' and 'targeting_pairs' exist), they are included in the full design.
    
    Parameters
    ----------
    model : dict
        Contains the fixed model information (keys "theta_pruned", "grid_T1", "grid_T2", "interaction_pairs",
        "selected_indices") and, optionally, targeting information (keys "theta_targeting", "targeting_pairs").
    t1_threshold, t2_threshold : float
        The thresholds at which to evaluate the survival function.
    n_points : int, optional
        Number of grid points for integration.
    integration_grid_T1, integration_grid_T2 : array-like, optional
        Custom integration grids; if None, a uniform grid over [0,1] is used.
    
    Returns
    -------
    S : float
        The survival probability estimate at (t1_threshold, t2_threshold).
    grad_full : numpy array
        The gradient of S with respect to the full parameter vector.
    """
    grid_df, _, _, weights = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    weights_flat = weights.ravel()
    X_fixed = create_bivariate_basis_functions(grid_df, model["grid_T1"], model["grid_T2"],
                                               model["interaction_pairs"], model["selected_indices"])
    if "theta_targeting" in model and "targeting_pairs" in model:
        X_target = create_targeting_basis_functions_bivariate(grid_df, model["targeting_pairs"])
        if hasattr(X_target, "numpy"):
            X_target = X_target.numpy()
        X_full = np.hstack([X_fixed, X_target])
        theta_full = np.concatenate([model["theta_pruned"], model["theta_targeting"]])
    else:
        X_full = X_fixed
        theta_full = model["theta_pruned"]
    f_full = np.exp(X_full @ theta_full)
    Z = np.sum(f_full * weights_flat)

    # Identify grid points within the survival region: {T1 >= t1_threshold, T2 >= t2_threshold}.
    grid_T1_vals = grid_df['T1']
    grid_T2_vals = grid_df['T2']
    region_mask1 = (grid_T1_vals <= t1_threshold) 
    region_mask2 = (grid_T2_vals <= t2_threshold)
    region_mask12 = (grid_T1_vals <= t1_threshold) & (grid_T2_vals <= t2_threshold)
    
    # Compute A = ∫_{region} exp{X(u)^T theta} du.
    A1 = np.sum(f_full[region_mask1] * weights_flat[region_mask1])
    A2 = np.sum(f_full[region_mask2] * weights_flat[region_mask2])
    A12 = np.sum(f_full[region_mask12] * weights_flat[region_mask12])
    
    S1 = A1/ Z
    S2 = A2/ Z
    S12 = A12/ Z
    S=1-S1-S2+S12
    
    # Compute gradients:
    region_mask = (grid_T1_vals > t1_threshold) & (grid_T2_vals > t2_threshold)
    grad_A = np.sum((f_full[region_mask] * weights_flat[region_mask])[:, None] * X_full[region_mask, :], axis=0)
    grad_Z = np.sum((f_full * weights_flat)[:, None] * X_full, axis=0)
    grad_full = (grad_A - S * grad_Z) / Z
    return S, grad_full





