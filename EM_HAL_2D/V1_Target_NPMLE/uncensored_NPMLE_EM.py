        # --- Construct Basis Grids ---
        K_main = 20
        grid_T1_main = np.percentile(data_biv['T1_tilde'], np.linspace(0, 100, K_main))
        grid_T2_main = np.percentile(data_biv['T2_tilde'], np.linspace(0, 100, K_main))
        K_interact = 5
        grid_T1_interact = np.percentile(data_biv['T1_tilde'], np.linspace(0, 100, K_interact))
