def compute_true_density_bivariate(t1_vals, t2_vals, mean=[0.5, 0.5], cov=[[0.05, 0.0], [0.0, 0.05]]):
    """
    Compute the true density of a truncated bivariate normal distribution over the grid defined by t1_vals and t2_vals.

    Parameters
    ----------
    t1_vals : 1D array
        Grid values for T1.
    t2_vals : 1D array
        Grid values for T2.
    mean : list, optional
        Mean vector of the bivariate normal.
    cov : 2x2 array, optional
        Covariance matrix.

    Returns
    -------
    density : 2D array
        True density evaluated on the meshgrid of t1_vals and t2_vals.
    """
    rv = multivariate_normal(mean=mean, cov=cov)
    # Compute normalization constant: probability mass inside [0,1]^2
    Z = rv.cdf([1, 1]) - rv.cdf([1, 0]) - rv.cdf([0, 1]) + rv.cdf([0, 0])

    T1, T2 = np.meshgrid(t1_vals, t2_vals)
    pos = np.dstack((T1, T2))
    pdf_vals = rv.pdf(pos)
    density = pdf_vals / Z
    return density

def compute_true_survival_bivariate(t1_vals, t2_vals, mean=[0.5, 0.5], cov=[[0.05, 0.0], [0.0, 0.05]]):
    """
    Compute the true survival function S(t1,t2)=P(T1 > t1, T2 > t2) on the grid defined by t1_vals and t2_vals.

    This is done by computing the true density using compute_true_density_bivariate,
    then obtaining the joint CDF via cumulative summation with appropriate integration weights,
    and finally applying the inclusion–exclusion formula.

    Parameters
    ----------
    t1_vals : 1D array
        Grid values for T1.
    t2_vals : 1D array
        Grid values for T2.
    mean : list, optional
        Mean vector.
    cov : 2x2 array, optional
        Covariance matrix.

    Returns
    -------
    survival : 2D array
        The survival function evaluated on the grid.
    """
    # Use the provided grid as the integration grid:
    grid_df, t1_grid, t2_grid, weights = get_integration_grid(t1_vals, t2_vals, n_points=len(t1_vals))
    true_density = compute_true_density_bivariate(t1_grid, t2_grid, mean, cov)

    # Compute the joint CDF by cumulative summation (make sure weights are applied)
    cdf = np.cumsum(np.cumsum(true_density * weights, axis=0), axis=1)
    # F_T1(t1): last row; F_T2(t2): last column
    F1 = cdf[-1, :]
    F2 = cdf[:, -1]
    survival = 1 - F1[np.newaxis, :] - F2[:, np.newaxis] + cdf
    return survival

