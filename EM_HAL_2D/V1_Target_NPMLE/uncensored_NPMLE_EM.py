def create_targeting_basis_functions_bivariate(data, targeting_pairs):
    """
    Create a bivariate targeting basis using indicator functions.

    For each targeting pair (t1, t2) in targeting_pairs, this function creates a column
    that equals 1 when both data['T1'] >= t1 and data['T2'] >= t2, and 0 otherwise.

    Parameters
    ----------
    data : pd.DataFrame
        DataFrame with at least columns 'T1' and 'T2'.
    targeting_pairs : list of tuples
        Each tuple is of the form (t1, t2).

    Returns
    -------
    basis_tensor : torch.Tensor
        A tensor of shape (n_samples, number_of_targeting_pairs).
    """
    indicators = {}
    for i, (t1, t2) in enumerate(targeting_pairs):
        col_name = f"targeting_indicator_{i}"
        # Create indicator column: 1 if (T1 >= t1) and (T2 >= t2), else 0.
        indicators[col_name] = ((data['T1'] >= t1) & (data['T2'] >= t2)).astype(int)
    indicators_df = pd.DataFrame(indicators, index=data.index)
    basis_tensor = torch.tensor(indicators_df.values, dtype=torch.float32)
    return basis_tensor

def targeting_M_step_bivariate(augmented_data, results, old_theta, targeting_pairs,
                               norm_constraint=20, n_points=50,
                               integration_grid_T1=None, integration_grid_T2=None):
    """
    Perform a targeting M-step update for the bivariate pruned model.

    The density model is defined as:

        f(T1, T2) = exp(fixed(T1, T2) + targeting(T1, T2)) / Z,

    where:

        fixed(T1, T2) = X_fixed * old_theta,   (built using create_bivariate_basis_functions)
        targeting(T1, T2) = X_targeting * alpha,

    and alpha is the only parameter being updated here.

    Parameters
    ----------
    augmented_data : pd.DataFrame
        Data on which to build the design matrices. Must contain columns 'T1', 'T2', and 'weights'.
    results : dict
        Dictionary with keys:
          - 'grid_T1'
          - 'grid_T2'
          - 'interaction_pairs'
          - 'selected_indices'
        These are used to construct the fixed (pruned) design matrix.
    old_theta : np.ndarray
        Fixed parameter vector from the previous (or pruned) model.
    targeting_pairs : list of tuples
        List of (t1, t2) pairs specifying the new targeting basis functions.
    norm_constraint : float, optional
        L1-norm constraint for the targeting coefficients.
    n_points : int, optional
        Number of integration grid points for the normalization integral.
    integration_grid_T1, integration_grid_T2 : array-like, optional
        If provided, these are used to create the integration grid.

    Returns
    -------
    updated_results : dict
        A dictionary containing the fixed parameters, targeting parameters, and an updated
        estimated density among other things.
    """
    start_time = time.time()

    # Retrieve fixed-design parameters from results
    grid_T1 = results['grid_T1']
    grid_T2 = results['grid_T2']
    interaction_pairs = results['interaction_pairs']
    selected_indices = results['selected_indices']

    # Build the fixed (pruned) design matrix on the data.
    X_fixed_data = create_bivariate_basis_functions(augmented_data, grid_T1, grid_T2,
                                                      interaction_pairs, selected_indices)
    # Build the targeting design matrix on the data.
    X_targeting_data = create_targeting_basis_functions_bivariate(augmented_data, targeting_pairs)

    # Build an integration grid for the normalization term.
    # (Assume get_integration_grid returns: grid_eval, int_t1, int_t2, weights)
    grid_eval, int_t1, int_t2, weights_grid = get_integration_grid(integration_grid_T1, integration_grid_T2, n_points)
    # Evaluate the fixed design on the grid.
    X_fixed_grid = create_bivariate_basis_functions(grid_eval, grid_T1, grid_T2,
                                                    interaction_pairs, selected_indices)
    # Evaluate the targeting design on the grid.
    X_targeting_grid = create_targeting_basis_functions_bivariate(grid_eval, targeting_pairs)

    end_time = time.time()
    print(f"Targeting M-step design matrix time (sec): {end_time - start_time:.4f}")

    # Fixed part of the linear predictor on data and grid.
    fixed_data = X_fixed_data @ old_theta
    fixed_grid = X_fixed_grid @ old_theta

    # Data weights and total weighted sample size.
    weights_data = augmented_data['weights'].values
    n_weighted = np.sum(weights_data)

    # area_elements are the integration weights (assumed to be given in weights_grid).
    area_elements = weights_grid.ravel()

    # Set up the optimization for the targeting coefficients alpha.
    r = X_targeting_data.shape[1]  # number of targeting basis functions
    alpha = cp.Variable(r)

    # Define the full predictor (fixed + targeting) on data and on the grid.
    L_data = fixed_data + X_targeting_data @ alpha
    L_grid = fixed_grid + X_targeting_grid @ alpha

    # Define the loss function.
    # The data term is the (weighted) negative log-likelihood on the data.
    data_term = -cp.sum(cp.multiply(weights_data, L_data))
    # The normalization term uses a log-sum-exp over the integration grid.
    norm_term = n_weighted * cp.log_sum_exp(cp.Constant(np.log(area_elements)) + L_grid)
    loss = data_term + norm_term

    constraints = [cp.norm1(alpha) <= norm_constraint]
    prob = cp.Problem(cp.Minimize(loss), constraints)

    # Warm-start with zeros.
    alpha.value = np.zeros(r)
    try:
        prob.solve(solver="ECOS")
    except Exception as e:
        print("ECOS solver failed: ", e, "\nUsing SCS instead.")
        prob.solve(solver="SCS")

    theta_targeting = alpha.value

    updated_results = {
        "old_theta": old_theta,                 # fixed part remains unchanged
        "theta_targeting": theta_targeting,       # new targeting coefficients
        "theta_pruned": old_theta,                # naming as in your pruned model
        "selected_indices": selected_indices,
        "grid_T1": grid_T1,
        "grid_T2": grid_T2,
        "interaction_pairs": interaction_pairs,
        "targeting_pairs": targeting_pairs
    }

    return updated_results

