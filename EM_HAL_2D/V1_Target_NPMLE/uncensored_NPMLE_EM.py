def E_step_bivariate_targeting(data, old_theta, theta_targeting, grid_T1, grid_T2,
                               interaction_pairs, selected_indices, targeting_pairs,
                               num_samples=5, n_points=50, integration_grid_T1=None, integration_grid_T2=None):
    """
    E–step for the targeted model: For each observation, impute missing coordinates
    from the full model f(T1,T2) = exp(fixed + targeting) / Z.
    """
    augmented_samples = []

    # Fully observed observations:
    fully_obs = data[(data['delta1'] == 1) & (data['delta2'] == 1)].copy()
    fully_obs['T1'] = fully_obs['T1_tilde']
    fully_obs['T2'] = fully_obs['T2_tilde']
    fully_obs['weights'] = 1.0
    augmented_samples.append(fully_obs[['T1', 'T2', 'weights']])

    # Case 1: T1 observed, T2 missing
    case_10 = data[(data['delta1'] == 1) & (data['delta2'] == 0)]
    for idx, row in case_10.iterrows():
        T1_val = row['T1_tilde']
        T2_min = row['T2_tilde']
        if integration_grid_T2 is None:
            t2_grid = np.linspace(T2_min, 1, n_points)
            dt = (1 - T2_min) / (n_points - 1)
            weights_1d = np.full_like(t2_grid, dt)
        else:
            t2_grid = np.array(integration_grid_T2)
            t2_grid = t2_grid[t2_grid >= T2_min]
            if len(t2_grid) < 2:
                t2_grid = np.linspace(T2_min, 1, n_points)
            weights_1d = compute_integration_weights(t2_grid)
        df_temp = pd.DataFrame({'T1': np.full(len(t2_grid), T1_val), 'T2': t2_grid})
        X_fixed = create_bivariate_basis_functions(df_temp, grid_T1, grid_T2, interaction_pairs, selected_indices)
        X_target = create_targeting_basis_functions_bivariate(df_temp, targeting_pairs)
        if isinstance(X_target, torch.Tensor):
            X_target = X_target.numpy()
        dens = np.exp(X_fixed @ old_theta + X_target @ theta_targeting)
        prob = dens / np.sum(dens * weights_1d)
        cdf = np.cumsum(prob * weights_1d)
        cdf /= cdf[-1]
        imputed_T2 = []
        for _ in range(num_samples):
            u = np.random.rand()
            j = np.searchsorted(cdf, u)
            imputed_T2.append(t2_grid[min(j, len(t2_grid)-1)])
        df_imputed = pd.DataFrame({'T1': T1_val, 'T2': imputed_T2})
        df_imputed['weights'] = 1.0 / num_samples
        augmented_samples.append(df_imputed)

    # Case 2: T1 missing, T2 observed
    case_01 = data[(data['delta1'] == 0) & (data['delta2'] == 1)]
    for idx, row in case_01.iterrows():
        T2_val = row['T2_tilde']
        T1_min = row['T1_tilde']
        if integration_grid_T1 is None:
            t1_grid = np.linspace(T1_min, 1, n_points)
            dt = (1 - T1_min) / (n_points - 1)
            weights_1d = np.full_like(t1_grid, dt)
        else:
            t1_grid = np.array(integration_grid_T1)
            t1_grid = t1_grid[t1_grid >= T1_min]
            if len(t1_grid) < 2:
                t1_grid = np.linspace(T1_min, 1, n_points)
            weights_1d = compute_integration_weights(t1_grid)
        df_temp = pd.DataFrame({'T1': t1_grid, 'T2': np.full(len(t1_grid), T2_val)})
        X_fixed = create_bivariate_basis_functions(df_temp, grid_T1, grid_T2, interaction_pairs, selected_indices)
        X_target = create_targeting_basis_functions_bivariate(df_temp, targeting_pairs)
        if isinstance(X_target, torch.Tensor):
            X_target = X_target.numpy()
        dens = np.exp(X_fixed @ old_theta + X_target @ theta_targeting)
        prob = dens / np.sum(dens * weights_1d)
        cdf = np.cumsum(prob * weights_1d)
        cdf /= cdf[-1]
        imputed_T1 = []
        for _ in range(num_samples):
            u = np.random.rand()
            j = np.searchsorted(cdf, u)
            imputed_T1.append(t1_grid[min(j, len(t1_grid)-1)])
        df_imputed = pd.DataFrame({'T1': imputed_T1, 'T2': T2_val})
        df_imputed['weights'] = 1.0 / num_samples
        augmented_samples.append(df_imputed)

    # Case 3: Both T1 and T2 missing
    case_00 = data[(data['delta1'] == 0) & (data['delta2'] == 0)]
    for idx, row in case_00.iterrows():
        T1_min = row['T1_tilde']
        T2_min = row['T2_tilde']
        if integration_grid_T1 is None or integration_grid_T2 is None:
            t1_grid = np.linspace(T1_min, 1, n_points)
            t2_grid = np.linspace(T2_min, 1, n_points)
            dt1 = (1 - T1_min) / (n_points - 1)
            dt2 = (1 - T2_min) / (n_points - 1)
            weights_2d = np.full((n_points, n_points), dt1 * dt2)
        else:
            t1_grid = np.array(integration_grid_T1)
            t2_grid = np.array(integration_grid_T2)
            t1_grid = t1_grid[t1_grid >= T1_min]
            t2_grid = t2_grid[t2_grid >= T2_min]
            if len(t1_grid) < 2 or len(t2_grid) < 2:
                t1_grid = np.linspace(T1_min, 1, n_points)
                t2_grid = np.linspace(T2_min, 1, n_points)
                dt1 = (1 - T1_min) / (n_points - 1)
                dt2 = (1 - T2_min) / (n_points - 1)
                weights_2d = np.full((n_points, n_points), dt1 * dt2)
            else:
                w1 = compute_integration_weights(t1_grid)
                w2 = compute_integration_weights(t2_grid)
                weights_2d = np.outer(w2, w1)
        T1_mesh, T2_mesh = np.meshgrid(t1_grid, t2_grid)
        df_temp = pd.DataFrame({'T1': T1_mesh.ravel(), 'T2': T2_mesh.ravel()})
        X_fixed = create_bivariate_basis_functions(df_temp, grid_T1, grid_T2, interaction_pairs, selected_indices)
        X_target = create_targeting_basis_functions_bivariate(df_temp, targeting_pairs)
        if isinstance(X_target, torch.Tensor):
            X_target = X_target.numpy()
        dens = np.exp(X_fixed @ old_theta + X_target @ theta_targeting)
        prob = dens / np.sum(dens * weights_2d.ravel())
        cdf = np.cumsum(prob * weights_2d.ravel())
        cdf /= cdf[-1]
        imputed_T1 = []
        imputed_T2 = []
        for _ in range(num_samples):
            u = np.random.rand()
            j = np.searchsorted(cdf, u)
            imputed_T1.append(df_temp.iloc[j]['T1'])
            imputed_T2.append(df_temp.iloc[j]['T2'])
        df_imputed = pd.DataFrame({'T1': imputed_T1, 'T2': imputed_T2})
        df_imputed['weights'] = 1.0 / num_samples
        augmented_samples.append(df_imputed)

    augmented_data = pd.concat(augmented_samples, ignore_index=True)
    return augmented_data

